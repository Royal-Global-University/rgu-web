                            Engineering " has been conducted successfully on 26/02/2024. It was organized by the
                            Department of Mechanical Engineering, featuring a renowned faculty member from ACE academy,
                            Hyderabad specializing in career guidance for Engineering students. <br>

                            The primary objective of the webinar was to enlighten B.Tech graduates, especially those in
                            Mechanical, Civil, and Computer Science disciplines, about various career pathways available
                            to them, focusing on opportunities through exams like GATE and IES, as well as admissions
                            for post-graduate studies in premier institutions like IITs and NITs.</p>

