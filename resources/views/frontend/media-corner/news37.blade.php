                Considering this, there are new opportunities for collaboration. An education exhibition could also be conducted in
                China by the Indian side. We always encourage Chinese students to study in India,” he added. He also mentioned that
                while China was the top source of international students globally over the last two decades, India has now emerged as
                the number one source of international students.
