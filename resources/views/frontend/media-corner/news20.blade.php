            During the visit, the delegation toured the university campus, including its academic blocks, laboratories, innovation
            centres, and other infrastructure facilities.
            <br><br>
            Welcoming the delegation, Prof. Alak Kumar Buragohain, Vice Chancellor, RGU, highlighted the potential for meaningful
            collaboration between RGU and Zimbabwe. “RGU offers scholarships for international students, including those from
            Zimbabwe. There is a growing need to integrate indigenous education systems with modern frameworks—and on this front, we
            can work together,” he said.
            <br><br>
            Mr. D.C. Damba, Director of Tertiary Education Program, Zimbabwe, expressed appreciation for the state-of-the-art
            infrastructure and enriching experience at RGU. “We are trying to move away from a colonial education model. Our focus
            now is on New Age technology, research and science—areas in which India excels. I have travelled to Russia, China, and
            France, but what I experienced at RGU is truly unique,” he remarked.
            <br><br>
            Ms. E. Chiwandika (Marara), Principal Officer, Higher Education Program, emphasised Zimbabwe’s focus on skill-based
            education. “We are glad to witness India’s success in providing practical education, and we look forward to formalising
            a collaboration that benefits our students,” she stated.
            <br><br>
            Echoing similar sentiments, Mr. Magunda noted, “Zimbabwe’s key challenge lies in building an economy rooted in
            heritage-based education. We envision an indigenous, people-centric education system that goes beyond industrialisation
            to embrace local innovation and self-reliance.”
            <br><br>
            Mr. Mbokochena emphasized the growing need for innovation and entrepreneurship. He highlighted how start-up culture,
            research-led innovation, and technology-driven education are critical to Zimbabwe’s future. The visit concluded on a
            positive note, with both sides expressing strong intent to work towards academic partnerships that promote innovation,
            skill development, and cultural exchange.
