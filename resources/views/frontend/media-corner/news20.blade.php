                Prof. (Dr.) Alak Kumar Buragohain, Vice Chancellor of RGU; Prof (Dr.) Diganta Munshi, Registrar; Prof. (Dr.) D. N.
                Singh, Registrar (Academic); Gurpreet Kaur Anand, Deputy Director, Office of International Affairs Royal Global
                University; Deans of various schools, senior faculty members, and other university officials. The interaction focused on
                mutual interests in innovation, skill-based education, and sustainable higher education practices.
