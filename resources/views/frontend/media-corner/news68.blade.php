                <span class="fw-bold"> GUWAHATI, November 15, 2025: </span>The Assam Royal Global University (RGU) today hosted an inspiring and insightful interactive session featuring Hon’ble Mr. Justice Ujjal Bhuyan, Judge, Supreme Court of India. Justice Bhuyan engaged in a profound discussion on the theme “From Constitution to Courtroom: Opportunities for the Next Generation of Law Graduates.” The programme has been organised by the Royal School of Law and Administration (RSLA) at Jyoti Mancha, RGU.
                <br><br>
                Addressing a packed audience of law students and faculty members, Justice Ujjal Bhuyan traced the Constitutional journey of India and the role of the judiciary in preserving its core values. Speaking on the transformative vision of the Constitution, he said, “Equality is its central pillar and we need an independent judiciary that remains insulated from external pressures”.
                <br><br>
                His detailed recounting of Nani Palkhivala’s rise, along with his arguments in Golak Nath, Bank Nationalisation, Privy Purse and the historic Kesavananda Bharati case, offered students a rare, insightful look into the evolution of constitutional jurisprudence and the enduring significance of the basic structure doctrine.
                <br><br>
                Justice Bhuyan also presented a candid assessment of the legal profession, reminding students that law demands discipline, integrity and sustained commitment. He urged young graduates to strengthen their foundations in procedure and evidence and to embrace litigation as the most enriching training ground for any lawyer. Noting that the Bar remains the “school of hard knocks,” he emphasised that the profession’s true rewards come from perseverance and ethical clarity rather than glamour. His remarks were widely seen as a grounded and inspiring message for the next generation of lawyers, urging them to carry forward the constitutional values that have shaped the nation’s legal landscape.
                <br><br>
                The event commenced with a warm felicitation of Justice Ujjal Bhuyan by Dr AK Pansari, Chancellor, Royal Global University. The welcome address was delivered by Prof. AK Buragohain, Vice-Chancellor of RGU who said that the interaction with Justice Bhuyan would serve as a significant inspiration for students, reinforcing the importance of discipline, diligence, and moral values in shaping successful legal careers. He commended the Royal School of Law and Administration for consistently fostering a culture of academic excellence and practical exposure.
