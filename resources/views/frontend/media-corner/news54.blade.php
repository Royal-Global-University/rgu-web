                To mark the occasion, Dr. Pansari led a plantation drive on the university campus, planting 62 saplings, symbolizing each year of his life dedicated to education, growth, and social upliftment. The initiative aims to contribute to environmental sustainability and encourage students and staff to maintain a lifelong relationship with nature. The plantation drive saw the active participation of faculty members, students, and staff, who pledged to nurture the saplings and turn the RGU campus into a greener and cleaner ecosystem.
