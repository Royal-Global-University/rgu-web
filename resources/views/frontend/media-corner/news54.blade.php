                <span class="fw-bold"> GUWAHATI, October 10, 2025: </span>Setting a unique example of service, compassion, and environmental responsibility, the 62nd birthday of Dr. Ashok Kumar Pansari, Chancellor of The Assam Royal Global University (RGU) has been celebrated today in a way that reflects deep social commitment rather than traditional festivity. There were no cakes, no sweets, and no ceremonial grandeur; instead, the day has been devoted entirely to giving back to society and nature.
