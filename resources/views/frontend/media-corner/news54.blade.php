                Speaking on the occasion, Dr. Pansari said, “Birthdays should not be about personal celebrations alone, but about making a meaningful difference in the lives of others. I believe service to humanity and care for the environment are the highest forms of celebration.” He expressed his gratitude to the RGU family for joining hands in the noble cause and encouraged everyone present to carry forward the spirit of service in their lives.
                <br><br>
                Prof. Alak Kumar Buragohain, Vice Chancellor of RGU, lauded the humanitarian gesture of the Chancellor and announced that this day will henceforth be observed as “Green Day” at Royal Global University every year. He said, “This initiative by Dr. Pansari is a torchbearer for all educational leaders. It reflects true leadership rooted in values, responsibility, and action. From today onwards, RGU will commemorate this day every year with activities that promote environmental conservation and community service.”
