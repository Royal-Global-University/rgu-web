            <p class="para1 text-dark pt-2">
                <span class="fw-bold"> GUWAHATI, November 18, 2025: </span> The Assam Royal Global University (RGU) today paid a soulful tribute to Assam’s beloved cultural icon, Zubeen Garg by launching a commemorative book titled “Zubeen: Twenty Songs and Seven Portraits”, a scholarship, and a memoriam in honour of the legendary artist. Organized under the aegis of the Dr Bhupen Hazarika Centre for Creativity, the event marked the birth anniversary of the heartthrob whose music continues to inspire millions.
                <br><br>
                The heartwarming programme was graced by Dr. A.K. Pansari, Chancellor of RGU; Prof AK Buragohain, Vice Chancellor; Prof. Amarjyoti Choudhury, Chair, Dr Bhupen Hazarika Centre for Creativity; Shri Ramanuj Dutta Choudhury, Executive Editor of The Assam Tribune; and Dr. Palme Borthakur, sister of Zubeen Garg, among other dignitaries, faculty, staff, and students. The tribute was further elevated by an evocative Sattriya performance by the acclaimed dancer Prerona Bhuyan, along with a nostalgic medley of Zubeen Garg’s evergreen classics presented by RGU students.
                <br><br>
                Edited by Sattyakee D’com Bhuyan, the book includes translations of twenty iconic songs of Zubeen Garg by Arkupal Ra Acharya, an evocative visual gallery drawn from photographs by Stephen Styris and seven essays contributed by Prof Amarjyoti Choudhury, Mitra Phukan, Dr Rakhee Kalita Moral, Dr Palme Borthakur, Ramanuj Dutta Choudhury, Banasmita Das and Rahul Karmakar. The book’s cover has been designed by Muku Madhav Baishya. On the other hand, the memoriam titled “Zubeen: the Road, the Music, the Life Perspectives” includes nine articles contributed by RGU faculty members and edited by Dr Pronami Bhattacharyya.
                <br><br>
                In his welcome address, Prof. Amarjyoti Choudhury expressed deep admiration for Zubeen Garg’s immense contribution to Assamese music and culture. He highlighted how the artiste embodied passion, versatility, inclusivity and an undying love for his homeland, noting that the new initiatives launched by RGU aim to preserve and celebrate his enduring artistic spirit.
                <br><br>
                Remembering the cultural icon with heartfelt emotion, Chancellor Dr. A.K. Pansari said that Zubeen Garg was not just a singer but a phenomenon who connected with people across generations. He emphasized that RGU will continue to honour his legacy through creative endeavours, adding that the newly launched scholarship and literary works will inspire students to pursue excellence in the arts.
                <br><br>
                Addressing the gathering, Shri Ramanuj Dutta Choudhury highlighted the cultural significance of Zubeen Garg’s contributions, stating that his artistic journey mirrored the aspirations of the people of Assam. He praised RGU’s efforts in preserving cultural heritage and nurturing young talent. Sharing personal reflections, Dr. Palme Borthakur spoke movingly about her brother’s boundless energy, compassion, and commitment to society.
