                <span class="fw-bold"> GUWAHATI, October 29, 2025: </span>Strengthening the bonds of friendship and collaboration between India and Bhutan, the 4th India-Bhutan Youth Summit 2025 concluded successfully at The Assam Royal Global University (RGU) here on Sunday. The Summit was jointly organised by the Centre for Escalation of Peace (CEP), India, the Royal Institute for Governance and Strategic Studies (RIGSS), Bhutan, the India-Bhutan Foundation (IBF), Bhutan, and Pallavan Learning Systems (PLS), India, and was held from October 22 to 30, 2025. The broad theme for this year’s Summit was “Gelephu Mindfulness City (GMC) and the Neighbourhood.”
