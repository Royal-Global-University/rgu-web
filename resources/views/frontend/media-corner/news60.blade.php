                On the final day of the Summit, 26th October, participants attended a special lecture by Dr. Alak Kumar Buragohain, Vice Chancellor of RGU. His talk explored the themes of Right Livelihood, Sustainable Development, and Buddhist Economics. “True progress lies not merely in economic growth, but in the cultivation of wisdom, compassion, and ethical values that guide our actions toward collective well-being,” he remarked. Professor Buragohain emphasized that education must move beyond material pursuits to embrace moral and spiritual dimensions, enabling youth to become responsible global citizens. His insightful address highlighted the interdependence of all beings and stressed the need to integrate science with religion, philosophy, sociology, and history to nurture holistic human development.
                <br><br>
                Earlier, on 22nd October, Mr. Choki Wangchuk from CEP delivered the opening address, warmly welcoming delegates from both countries. Mr. Hasta Bdr. Rai from RIGSS, Bhutan, extended gratitude to RGU and the partner organisations for their support and hospitality.
                <br><br>
                The nine-day programme offered participants a blend of learning, exposure, and adventure. It included introductions to both countries, a three-day trek through the scenic landscapes of Shillong, meaningful discussions on the Summit theme, and interactions with eminent personalities from India and Bhutan.
                <br><br>
                At the conclusion of the Summit, participants shared their reflections and insights gained throughout the journey. The India-Bhutan Youth Summit aims to deepen mutual understanding among young people, strengthen appreciation for the enduring friendship between the two nations, and create a network of future ambassadors committed to nurturing this special relationship for years to come.
