            <p class="para1 text-dark pt-2">
                <span class="fw-bold"> GUWAHATI, March 10, 2026: </span>The Assam Royal Global University (RGU) has held a
                Quiz and a Debate Competition on “Youth Interaction on Act East Policy and Assam’s Emerging Role” here
                today. The event was organised by the Department of Economics and the Internal Quality Assurance Cell
                (IQAC), RGU, in collaboration with the Act East Policy Affairs Department, Government of Assam. The
                programme brought together students from colleges across Assam, and officials from the Act East Policy
                Affairs Department for a meaningful exchange of ideas on the growing strategic significance of Assam and the
                Northeast in India’s foreign policy framework.
                <br><br>
                Delivering the keynote address, Shri Rajiv Bora, IAS (Retd.), former Additional Chief Secretary of Assam and
                APSC Chairman, reflected on the relevance of the Act East Policy in the contemporary global context.
                Emphasising that the Act East Policy is a crucial pillar of the Government of India’s foreign policy, he
                highlighted the Northeast’s geographical and strategic position as a natural bridge between India and
                Southeast Asia.
                <br><br>
                Shri Bora observed that the region, endowed with abundant natural and cultural resources, can serve as the
                fulcrum of India’s engagement with neighbouring countries under the Act East Policy. However, he cautioned
                that the effective implementation of the policy depends largely on achieving a minimum threshold of
                development in the Northeast, particularly in terms of infrastructure. He also stressed the importance of
                enhancing people-to-people contacts and cultural exchanges with neighbouring countries to strengthen
                regional cooperation.
                <br><br>
                Shri Manavendra Pratap Singh, IAS, Secretary to the Government of Assam, Act East Policy Affairs Department,
                spoke about the government’s efforts to leverage the Act East Policy for the socio-economic transformation
                of the region. He pointed out that many cultural practices in Northeast India have historical connections
                with Southeast Asia, illustrating long-standing civilisational linkages.
                <br><br>
                He further highlighted major developments that could strengthen Assam’s global connectivity, including the
                anticipated growth of Lokpriya Gopinath Bordoloi International Airport in Guwahati as a major regional hub
                in the coming years. Referring to the upcoming semiconductor project at Jagiroad, he said such initiatives
                would open new economic opportunities and place Assam more prominently on the global map. He also envisioned
                Guwahati emerging as a key centre linking cities across Southeast Asia.
                <br><br>

                Shri Sazzad Alam, ACS, Additional Secretary to the Government of Assam, Act East Policy Affairs Department
                conducted the quiz competition as part of the programme, which witnessed enthusiastic participation. The
                topic for the debate competition was, “Assam can become India's Logistics Hub for Southeast Asian trade
                under the Act East Policy”.
                <br><br>
                Earlier in the inaugural session, Prof Shiela Bora delivered the welcome address, noting that the spirit of
                the Act East Policy is not entirely new to the Northeast. She observed that the region historically
                maintained vibrant trade and cultural exchanges across borders since ancient times.
                <br><br>
                Addressing the gathering, Prof A.K. Buragohain, Vice Chancellor of RGU, emphasised that universities play a
                vital role in facilitating such engagements. He remarked that academic research and intellectual discourse
                can significantly contribute to the effective understanding and implementation of important national
                policies such as the Act East Policy.
                <br><br>
                Prof Dhrubajyoti Borah, Advisor to the Chancellor and Author-in-Residence at RGU, spoke on the historical
                significance of the Southern Silk Route, describing it as a vibrant trade corridor that once passed through
                regions such as present-day Biswanath Chariali in Assam. He pointed out that these ancient routes were not
                merely channels for trade in goods but also pathways for the exchange of ideas, cultures, and knowledge. The
                programme concluded with a vote of thanks delivered by Prof Swabera Islam, Advisor to the Department of
                Economics, RGU.
