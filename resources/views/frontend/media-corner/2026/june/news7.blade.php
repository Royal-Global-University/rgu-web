                <span class="fw-bold"> GUWAHATI, June 16, 2026: </span>
                The Assam Royal Global University (RGU) signed a Memorandum of Understanding (MoU) with the Nagaland Police today in a significant step towards expanding educational opportunities for the families of police personnel. The agreement was formalised at the Office of the Director General of Police in Kohima in the presence of senior officials from Nagaland Police and RGU.
                <br><br>
                The MoU was signed by Shri Rupin Sharma, IPS, Director General of Police, Nagaland, on behalf of the Nagaland Police, and Dr. D. N. Singh, Registrar (Academics), representing The Assam Royal Global University.
                <br><br>
                Speaking on the occasion, Shri Rupin Sharma highlighted the importance of the collaboration and expressed confidence that it would greatly benefit the wards and dependents of Nagaland Police personnel. He also expressed hope that the collaboration would be effectively utilised to benefit the community, particularly the children and dependents of Nagaland Police personnel, by facilitating access to quality higher education.
                <br><br>
                Under the partnership, RGU will introduce two dedicated scholarship categories—Royal Shaurya and Royal Suraksha—designed to support the higher education aspirations of eligible dependents and wards of defence and security personnel, including serving personnel, ex-servicemen, personnel with disabilities, and those who have died in harness. The initiative aims to ensure that deserving students receive access to quality education and professional development opportunities.
                <br><br>
                Dr. D. N. Singh said, “It is a matter of immense honour and privilege for our university to enter into this MoU with the Nagaland Police. Through this partnership, we seek to recognize and support the invaluable contributions of our police personnel by ensuring that their families have access to quality higher education opportunities. We are committed to empowering the next generation through academic excellence, scholarships, and holistic development.”
                <br><br>
                The MoU signing ceremony was attended by several senior officials of the Nagaland Police, including Shri Renchamo P. Kikon, IPS, Additional Director General of Police (Administration); Shri Videlalie Zashumo, IPS, Inspector General of Police (Administration); Shri Rothihu Tetseo, IPS, Inspector General of Police (Intelligence); Shri Jaspir Singh, IPS, Inspector General of Police (Range); Shri Kevithuto Sophie, IPS, Inspector General of Police (Armed Battalion–IR); Shri Changkei Konyak, Inspector General of Police (Technical); Shri Uniel Kichu, IPS, Deputy Inspector General of Police (Range, Kohima); Shri Chumrenthung, IPS, Deputy Inspector General of Police (CID); Shri Yangba Konyak, IPS, Deputy Inspector General of Police (Intelligence); Shri Lakha Koza, IPS, Deputy Inspector General of Police (IR North); Shri Vekhosa Chakesang, IPS, Deputy Inspector General of Police (Administration); and Shri Watichuchang Jamir, NPS, Assistant Inspector General of Police (Coordination).
