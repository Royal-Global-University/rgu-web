                ensuring that their families have access to quality higher education opportunities.”
                <br><br>
                Under the MoU, RGU will introduce two dedicated scholarship categories—Royal Shaurya and Royal Suraksha—for
                the dependents and wards of defence personnel, including serving personnel, ex-servicemen, personnel with
                disabilities, and those who have died in harness.
                <br><br>

                The University will offer the Royal Shaurya Scholarship, providing 100% tuition fee waiver to the families of martyrs and gallantry awardees, while the Royal Suraksha Scholarship will provide 50% tuition fee concession to the wards of serving and retired defence personnel.
