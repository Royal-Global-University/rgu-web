                <span class="fw-bold"> GUWAHATI, June 10, 2026: </span>
                In a significant boost to agricultural education and research in the region, Sri S. K. Bhalla, Secretary, North Eastern Council (NEC), Government of India, Ministry of Development of North Eastern Region (DoNER), inaugurated the newly established Laboratories of Agricultural Sciences at The Assam Royal Global University (RGU) today in the presence of Prof Alak Kumar Buragohain, Vice Chancellor of RGU, Dr Bidyut Kumar Sarmah, Director, NECAB, Assam Agricultural University, Jorhat, apart from deans, faculty members and other high officials.
