            <p class="para1 text-dark pt-2">
                <span class="fw-bold"> GUWAHATI, June 18, 2026: </span>
                The Dr. Bhupen Hazarika Centre for Creativity of The Assam Royal Global University (RGU) today organized a
                special literary and cultural programme at Jyoti Mancha to mark the publication and launch of two
                commemorative volumes titled “Jyoti Prasad Agarwala: Twenty Songs and Seven Portraits” and “Bishnu Prasad
                Rava: Twenty Songs and Seven Portraits.”
                <br><br>
                The programme was graced by Prof. Bijoy H. Boruah, Senior Professor and Advisor, IIT Jammu; noted cultural
                activist Shri Hemraj Rava, son of Kalaguru Bishnu Prasad Rava; and Smt. Jnanashree Agarwala Pathak and Smt.
                Satyashree Agarwala Das, daughters of Rupkonwar Jyotiprasad Agarwala. The occasion was further enriched by
                the presence of Dr. A. K. Pansari, Chancellor of Royal Global University. Edited by Sattyakee D’com Bhuyan,
                Associate Dean, Department of Social Work, RGU, the volumes pay tribute to the enduring artistic genius,
                intellectual legacy, and immense cultural contributions of two of Assam’s most revered icons—Rupkonwar Jyoti
                Prasad Agarwala and Kalaguru Bishnu Prasad Rava.
                <br><br>
                Delivering the keynote lecture, Prof. Bijoy H. Boruah situated Assamese cultural modernity within the
                broader framework of South Asian modernity. Reflecting on the contributions of Assam’s celebrated cultural
                trinity—Jyoti Prasad Agarwala, Bishnu Prasad Rava, and Dr. Bhupen Hazarika—he observed that their artistic
                creations gave Assamese society “self-consciousness and dignity.” He noted that while much has been written
                about these iconic personalities, their contributions are rarely examined through wider theoretical
                perspectives.
                <br><br>
                Prof. Boruah highlighted the role of these figures as “organic intellectuals” who articulated the
                aspirations and cultural identity of the Assamese people. Referring to the ideas of Italian Marxist thinker
                Antonio Gramsci, particularly the concept of cultural hegemony, he underscored how these visionaries shaped
                public consciousness through art, literature, music, and social engagement. He further emphasized the
                continuity and relevance of Assamese cultural modernity in contemporary times.
                <br><br>
                Addressing the gathering, Chancellor Dr. A. K. Pansari remarked that Jyoti Prasad Agarwala and Bishnu Prasad
                Rabha would forever remain alive in the hearts and minds of the Assamese people. He noted that the
                publication of these books in English would help introduce their creativity, vision, and genius to a wider
                global audience.
                <br><br>
                Earlier, welcoming the guests and participants, Prof. Amarjyoti Choudhury, Professor Emeritus and Chair
                Professor at the Dr. Bhupen Hazarika Centre for Creativity, reflected on the complementary legacies of the
                two luminaries. “If Jyoti Prasad Agarwala is the calmness of dawn, Bishnu Prasad Rava is the violent storm,”
                he remarked, adding that both visionaries gifted Assam a philosophy of unity, harmony, and cultural
                awakening. He noted that the publication of these volumes was a celebration of their enduring spirit and
                contributions to Assamese civilization.
                <br><br>
                Shri Hemaraj Rava, son of Kalaguru Bishnu Prasad Rava, also addressed the gathering and expressed his
                happiness and gratitude to RGU for bringing out the commemorative publication, which he described as a
                meaningful tribute to his father’s legacy.
                <br><br>
                The event brought together academicians, artists, writers, students, and cultural enthusiasts in a
                collective celebration of Assam’s rich literary, musical, and artistic traditions. The programme concluded
                with a vote of thanks delivered by Sattyakee D’com Bhuyan, who informed the audience that the books form
                part of an ongoing publication series titled “Twenty Songs and Seven Portraits,” conceived to ensure
                continuity in documenting and celebrating the lives and works of Assam’s cultural icons.
