            <p class="para1 text-dark pt-2">
                <span class="fw-bold">GUWAHATI, August 20, 2026:</span>The Assam Royal Global University (RGU) has
                received a three-year Start-Up Grant for Induction into Biomedical and Health Research under the Human
                Resource Development (HRD) Scheme of the Department of Health Research, Government of India, for 2026-27,
                officials said.
                <br><br>
                RGU is the only private university from the Northeast to receive the grant under the scheme this year,
                marking a significant achievement for the university's research programme in biomedical and health sciences.
                <br><br>
                The project, sanctioned a grant of Rs 23,25,924, is titled “Fabrication of Curcumin and Hyaluronic Acid
                Co-loaded Araucaria Gum-based Nanosponge Gel for Improved Wound Healing Applications.”
                <br><br>
                Dr Rajat Subhra Dutta, Associate Professor, Royal School of Pharmacy, RGU, is the Principal Investigator,
                while Dr Anju Das, Assistant Professor, Royal School of Pharmacy, is the Co-Principal Investigator.
                <br><br>
                The research team will work on developing a novel wound-healing formulation using curcumin and hyaluronic
                acid encapsulated in nanosponges and incorporated into a gel base prepared from Araucaria gum.
                <br><br>
                According to Dr Dutta, the proposed formulation is aimed at providing sustained drug release and improved
                therapeutic delivery, with the potential to accelerate wound healing.
                <br><br>
                “Wounds that remain untreated can have prolonged healing periods due to microbial infections at the wound
                site and may lead to serious complications, including sepsis. There is, therefore, a need to explore natural
                biomaterial-based drug delivery systems as alternatives to conventional wound-healing therapies,” Dr Dutta
                said.
                <br><br>
                The project will focus on the extraction and characterisation of gum from Araucaria columnaris, an
                underutilised natural resource, followed by the development and optimisation of the nanosponge gel
                containing curcumin and hyaluronic acid. The wound-healing efficacy of the formulation will subsequently be
                evaluated in animal models.
                <br><br>
                The researchers said the proposed approach is novel as it combines the encapsulation of curcumin and
                hyaluronic acid in nanosponges with an Araucaria gum-based gel. The formulation is expected to facilitate
                sustained release and effective delivery of the therapeutic agents.
                <br><br>
                Dr Dutta said the research could eventually lead to a safe, eco-friendly and cost-effective wound-care
                product, with potential applications in improving existing wound-healing therapies.
