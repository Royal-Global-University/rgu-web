            <p class="para1 text-dark pt-2">
                <span class="fw-bold"> GUWAHATI, August 4, 2026: </span>The Royal School of
                Fashion Design and Technology (RSFT) at The Assam Royal Global University (RGU) on Tuesday launched the
                second edition of its annual lookbook, Threads of Tomorrow–2026, showcasing the creative work of its
                graduating batch. The University also inaugurated a new fashion studio, The Design Atelier, during the
                programme.
                <br><br>
                The fashion studio was inaugurated by acclaimed Shillong-based fashion designer and entrepreneur Daniel Syiem, while the lookbook was unveiled by Ashwani Kumar, Secretary to the Government of Assam, Information Technology Department, along with Sri Ankur Pansari, Pro Chancellor RGU, Daniel Syiem, and others.
                <br><br>
                The 2026 edition of the lookbook features 70 original ensembles developed under 14 design concepts by the graduating students of RSFT. The collections are the outcome of months of research, concept development, design experimentation, and garment construction, reflecting a range of contemporary themes and design approaches.
                <br><br>
                Speaking on the occasion, renowned fashion designer Daniel Syiem encouraged the graduating students to pursue their passion with commitment and perseverance. “Fashion is an industry driven by passion. Success comes to those who believe in their creativity and continue learning every day. I am truly impressed by the quality of work displayed by the students of Royal Global University. Their collections demonstrate originality, technical excellence, and immense creative potential. I have no doubt that many of them have the ability to make a mark not only in India but also on the global fashion stage,” he said.
                <br><br>
                Addressing the gathering, Ashwani Kumar described fashion as an expression of human creativity rooted in culture and everyday life. “God is the ultimate creator, and creativity is reflected in everything around us. Fashion exists in every aspect of our lives and serves as a powerful medium to celebrate culture and identity. I encourage the students to become innovators, entrepreneurs, and job creators. Do not wait only for employment opportunities—create your own opportunities, build your own brands, and follow your dreams,” he said.
                <br><br>

                Design Mentor Akriti Mazumdar said the lookbook reflected the students' commitment, creativity, and technical skills developed during their academic journey. She also acknowledged the contribution of Technical Mentor Asif Mazid in guiding the students through the execution of their final collections.
                <br><br>
                The Royal School of Fashion Design and Technology offers undergraduate programmes in fashion design with training in areas including textiles, garment construction, pattern making, fashion illustration, and digital design. The curriculum combines classroom learning with practical exposure through design projects, workshops, and internships to prepare students for careers in the fashion industry.
                <br><br>
                The annual Threads of Tomorrow lookbook serves as a documented portfolio of the graduating batch and provides a platform for students to present their design collections before industry professionals, academicians, and the wider public.
