                <span class="fw-bold"> GUWAHATI, August 12, 2026: </span>On the occasion of Librarian’s Day, The Assam Royal University (RGU) organised a special programme titled “Walk to the Library” on Wednesday, August 12, with the objective of inspiring and enthusing the university fraternity to embrace reading as an integral part of academic and personal life.
                <br><br>
                The programme was organised with the support of the Department of Library and Information Science and the Dr. Bhupen Hazarika Centre for Creativity, RGU, as part of its Creative Talks series.
                <br><br>
                Professor Emeritus and Chair, Dr. Bhupen Hazarika Centre for Creativity, RGU, Prof. Amarjyoti Choudhury, Chancellor Dr. A. K. Pansari, Pro Chancellor Ankur Pansari, Vice Chancellor Prof. Alak Kumar Buragohain, along with faculty members, students and members of the university fraternity, participated in the walk. The procession began from the university premises and proceeded towards the Central Library, symbolising a collective movement towards books, knowledge and the enriching experience of reading.
                <br><br>
                Following the walk, the participants spent time in the library reading and exploring its resources. The programme provided an opportunity for students and members of the university community to experience the library not merely as a repository of books, but as a vibrant space for reflection, learning, discovery and creativity.
                <br><br>
                Addressing the gathering, Chancellor Dr. A. K. Pansari emphasised the importance of cultivating a sustained reading habit among students. He encouraged the young learners to make reading a regular part of their lives, observing that books broaden perspectives, deepen understanding and contribute to the overall development of an individual.
                <br><br>
                Prof. Amarjyoti Choudhury also addressed the gathering, highlighting the enduring value of books and the transformative power of reading. He encouraged students to develop a meaningful relationship with books and knowledge, stressing the need to create an ambience where reading becomes a shared and enriching experience.
                <br><br>
                The “Walk to the Library” was conceived as a symbolic expression of solidarity with the culture and ambience of reading. Bringing together the university’s leadership, faculty, students and staff, the initiative sought to reinforce the message that libraries remain vital spaces for intellectual growth, imagination and lifelong learning.
