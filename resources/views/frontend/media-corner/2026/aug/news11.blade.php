            <p class="para1 text-dark pt-2">
                <span class="fw-bold">GUWAHATI, August 26, 2026:</span>The Assam Royal Global University (RGU) has signed a
                Memorandum of Understanding (MoU) with the Star Cement Charitable Trust, the voluntary humanitarian trust of
                Star Cement Limited, marking an important industry–academia collaboration aimed at developing a structured
                framework and action plan for reducing the carbon footprint of schools.
                <br><br>
                The MoU was signed yesterday at the city office of Star Cement by Prof. Diganta Munshi, Registrar
                (Administration) and Director, IQAC, RGU, on behalf of The Assam Royal Global University, and Sri Pradeep
                Purohit, Chief Operating Officer, Star Cement, on behalf of the Star Cement Charitable Trust.
                <br><br>
                For conducting the assigned task, a proposed budget of Rupees Two Lakhs has been allocated. The agreement
                will come into effect from September 1, 2026, and will remain valid for a period of two years.
                <br><br>
                In this context, Sri Pradeep Purohit said, “The collaboration seeks to strengthen industry-academia
                cooperation through joint research, consultation, assessment and implementation of sustainable practices
                relevant to the cement, infrastructure and allied sectors”. As part of the initiative, the two organisations
                will jointly identify two schools in the Sonapur area, as nominated by the Star Cement Charitable Trust, for
                undertaking carbon footprint reduction initiatives.
                <br><br>
                Prof. Diganta Munshi stated that RGU will conduct comprehensive assessments, studies and analyses to
                determine the existing carbon footprint levels of the identified schools. Based on the findings, the
                University will develop a structured framework comprising practical strategies, appropriate methodologies
                and actionable measures aimed at reducing and, where feasible, eliminating carbon emissions and other
                contributors to the schools’ carbon footprint.
                <br><br>

                The University will prepare and submit a comprehensive report with recommendations to the Star Cement
                Charitable Trust by November 2026. The report will serve as the basis for identifying and prioritising
                suitable interventions for implementation.
                <br><br>
                The Star Cement Charitable Trust will review the recommendations and undertake responsibility for
                implementing the mutually agreed measures, including providing the necessary resources and execution
                support, as well as monitoring the outcomes of the initiatives.
                <br><br>
                The collaboration is expected to provide a practical model for promoting environmental sustainability and
                carbon-conscious practices in educational institutions, while demonstrating the potential of
                industry-academia partnerships in addressing pressing environmental challenges.
