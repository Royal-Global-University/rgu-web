                <br><br>
                In an official communication, Prof. Y. P. Verma, Registrar of Panjab University, stated that Dr. Mahanta's appointment would significantly strengthen the objectives of the Chair. “Prof. Mahanta’s valuable suggestions and academic leadership will help the Chair achieve its objectives of promoting the literary, cultural, philosophical and spiritual legacy of Srimanta Sankardev at the national and international levels,” he said.
