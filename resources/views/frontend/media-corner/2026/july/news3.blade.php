                Expressing his delight on the appointment, Dr. Mahanta said, “My thrust area under this Chair will be the translation of the works of Srimanta Sankardev and Madhavdev into Punjabi and English, besides preparing scholarly monographs on the diverse contributions of these two great saints of Assam. I also plan to undertake a series of publications highlighting different dimensions of the Bhakti Movement led by Srimanta Sankardev in Assam.”
                <br><br>
                As Chair Professor, Dr. Mahanta will spearhead a range of academic and outreach activities aimed at promoting the life, philosophy, literature, culture and enduring legacy of Srimanta Sankardev. The Chair will organize special lectures for students, extension lectures, seminars and academic interactions across various departments and affiliated colleges of Panjab University.
                <br><br>
                In addition, Dr. Mahanta will provide academic leadership and mentorship in planning and implementing the future programmes of the Srimanta Sankardev Chair, including research initiatives, publications, collaborative projects and other scholarly activities to further enhance the Chair’s national and international outreach and impact.
