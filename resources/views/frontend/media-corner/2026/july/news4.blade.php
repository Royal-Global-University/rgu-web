                <span class="fw-bold"> GUWAHATI, July 29, 2026: </span>
                The Assam Royal Global University (RGU) today commenced Deeksharambh 2026, its annual Student Induction
                Programme for newly admitted undergraduate students. The comprehensive 19-day induction programme, designed
                to familiarise students with the University's academic environment, values, and opportunities, will continue
                from July 29 to August 16, 2026.
                <br><br>
                The inaugural session was graced by Prof. Saroj Kanta Barik, Vice-Chancellor of North-Eastern Hill
                University (NEHU), as the Chief Guest, while the second session featured an inspiring address by Shri
                Armstrong Pame, IAS, Commissioner, Minority Affairs, Government of Manipur. The programme was held in the
                august presence of Dr. A. K. Pansari, Chancellor, Prof. Alak Kumar Buragohain, Vice-Chancellor, senior
                university officials, faculty members, parents and newly admitted students.
                <br><br>
                Addressing the students, Prof. Saroj Kanta Barik urged them to cultivate curiosity, integrity, innovation,
                and a lifelong passion for learning. Highlighting the importance of interdisciplinary education, he said
                that the future belongs to interdisciplinary, multidisciplinary and cross-disciplinary learning, as such
                approaches equip students to address complex societal challenges such as poverty, water scarcity, pollution,
                and biodiversity conservation.
                <br><br>
                He encouraged students to pursue their interests with dedication and strive for excellence. Stressing the
                value of collaboration, he remarked that classmates are not competitors but partners in learning. He also
                urged students to make the best use of their teachers' guidance and to develop their individuality and
                personality. "Every discipline has its own significance. Never underestimate yourself. You possess immense
                potential and the ability to achieve anything you aspire to. The only limitation is not recognising your own
                capabilities. You have the same potential as those whom you admire as your role models," he said.
                <br><br>
                Welcoming the freshers, Chancellor Dr. A. K. Pansari highlighted RGU's commitment to providing holistic,
                value-based and industry-oriented education. He encouraged students to lead purposeful lives and develop an
                entrepreneurial mindset, urging them to become job creators rather than job seekers.
                <br><br>
                Emphasising the University's growing global character, he noted that nearly 10 per cent of this year's newly
                admitted students come from 23 different countries, providing an enriching multicultural environment and a
                truly global learning platform. He urged the students to take pride in calling themselves "Royalites" and
                make the most of the diverse opportunities available at the University.
                <br><br>
                In his address, Vice-Chancellor Prof. Alak Kumar Buragohain emphasised the importance of discipline, innovation, research, and interdisciplinary learning in shaping successful careers. He encouraged students to actively participate in academic, cultural, sports, innovation, and community engagement activities, which form an integral part of the RGU experience and contribute to their holistic development.
                <br><br>
                During the 19-day Student Induction Programme, the newly admitted students will participate in a series of academic orientation sessions, interactive discussions, workshops, and activities designed to familiarise them with the University's academic framework, student support services, research opportunities, innovation ecosystem, and vibrant campus life.
