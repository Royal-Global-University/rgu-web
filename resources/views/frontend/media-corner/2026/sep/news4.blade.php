            <p class="para1 text-dark pt-2">
                <span class="fw-bold"> GUWAHATI, September 18, 2026: </span>The Assam Royal Global University (RGU) observed
                Zubeen Diwas today to honour the enduring presence, music and legacy of legendary artiste Zubeen Garg. The
                programme commenced with a deeply symbolic gesture as Garima Saikia Garg, wife of Zubeen Garg, planted a
                Nahor sapling on the university campus.
                <br><br>
                Organised by the Dr. Bhupen Hazarika Centre for Creativity (DBHCC), the programme was graced by Garima
                Saikia Garg, Dr. A. K. Pansari, Chancellor, RGU, and members of the university community, who came together
                to celebrate Zubeen Garg’s remarkable artistic journey and his immense contribution to Assamese music and
                culture.
                <br><br>
                In his welcome address, Dr. Amarjyoti Choudhury, Professor Emeritus and Chair, Dr. Bhupen Hazarika Centre
                for Creativity (DBHCC), Royal Global University, said, “Today, we are coming together not to mark an ending,
                but to honour a presence that continues to inspire us through music, memories and love. He is always with
                us.”
                <br><br>
                Dr. Choudhury further stated that the DBHCC proposes to conduct research on four significant aspects of
                Zubeen Garg’s artistic contribution and personality. These include: a) Profiling of Zubeen Garg’s voice and
                vocal ability; b) His multilingual adaptability; c) The way he took Assamese folk music to the outside
                world; and d) His idea that art is all about freedom.
                <br><br>
                Expressing her gratitude to Royal Global University, Garima Saikia Garg thanked the university for taking
                several initiatives to study and research the life and creativity of Zubeen Garg, as well as his
                contribution to Assamese society and humanity. She also recollected Zubeen’s exceptional style of expression
                and his distinctive personality since the time they first met each other.
                <br><br>
                Dr. Palme Borthakur, sister of Zubeen Garg, also addressed the audience and spoke about Zubeen’s
                multifaceted personality, his deep connection with music and people, and the values that shaped his life and
                creative journey. She expressed her gratitude to Royal Global University for remembering Zubeen and for
                initiating academic research to document and understand his enduring contribution to music, culture and
                society.
                <br><br>
                Their words brought a deeply personal dimension to the occasion, offering glimpses of Zubeen Garg beyond the
                celebrated musician—as a husband, brother, family member and a human being whose presence touched countless
                lives.
                <br><br>
                The occasion also featured cultural performances by RGU students and faculty members in tribute to Zubeen
                Garg, celebrating his music and artistic contributions and reflecting the deep emotional connection his
                music continues to evoke across generations.
