                <br><br>
                Explaining the ideological dimensions of Naxalism, Singh said the movement has historically thrived on
                grievances, deprivation and narratives that portray a conflict between people and the State, often
                accompanied by the romanticisation of armed rebellion.
                <br><br>
                During her presentation, she observed that a movement once regarded as one of India’s biggest internal
                security challenges had reached its end phase in 2026. She attributed this transformation to the
                Government’s sustained efforts to extend the presence of the State into formerly Maoist-affected regions
                through infrastructure development, welfare delivery, rehabilitation and administrative outreach.
                <br><br>
                Singh emphasised that the next phase should focus on rebuilding erstwhile Maoist-affected societies through
                development, good governance and active community participation. She stressed that the face of governance in
                these regions should gradually shift from a predominantly security-oriented presence to public service
                delivery, with institutions such as schools, hospitals, banking facilities and other essential services
                becoming more visible and accessible to local communities.
                <br><br>
                The interactive session witnessed enthusiastic participation from a large number of students. Several
                students raised questions on insurgency, extremism, counter-insurgency strategies, governance and the
                challenges involved in sustaining peace and development in formerly affected regions. Singh responded to the
                queries and engaged with the students on the broader social, political and security dimensions of the issue.
