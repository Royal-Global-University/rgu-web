                <span class="fw-bold"> GUWAHATI, September 11, 2026: </span>Author, advocate, philosopher, and modern spiritual seeker Kartikeya Vajpai interacted with students and faculty members of The Assam Royal Global University (RGU) at a ‘Meet-the-Author’ programme organised by the Office of Student Affairs on Friday.
                <br><br>
                Kartikeya, author of The Unbecoming, published by Penguin Random House India, spoke about the distinction between intellect and wisdom, the limitations of attachment to the known, and the importance of developing the ability to observe and experience life with greater awareness.
                <br><br>
                Addressing the gathering, Kartikeya said that the difference between intellect and wisdom was essentially the difference between “thinking and experience”. According to him, knowledge already acquired can sometimes create an attachment to what one knows, giving rise to ego and preventing an individual from looking at familiar subjects or situations from a fresh perspective.
                <br><br>
                He also spoke about the impact of the digital and social media age on attention spans. Constant exposure to algorithms, he observed, often works by triggering what is already familiar to individuals. “The only way to take care of this is to ignite the observer in each one of you,” he said, encouraging students to cultivate awareness beyond their immediate thoughts and experiences.
                <br><br>
                Kartikeya further observed that while intellect is a cognitive function and may differ from person to person, wisdom is universal. “It is not something that you are born with; you have to train yourself,” he said, adding that becoming a seeker and being fully present in each moment were essential to developing wisdom.
                <br><br>
                Kartikeya has an extensive corporate experience in marketing and is also the founder of a New Delhi-based law firm, where he advises clients on diverse legal and business matters. His debut novel, The Unbecoming, explores questions of identity, purpose, fulfilment and self-discovery, drawing upon his engagement with Advaita Vedanta, Buddhist philosophy, Transcendental Meditation, Kriya Yoga and other contemplative traditions.
                <br><br>
                The book carries forewords by His Holiness the 14th Dalai Lama and Swami Sarvapriyananda. In his foreword, the Dalai Lama describes The Unbecoming as a work that examines the human condition through questions of identity, ego, attachment and impermanence, while highlighting life’s struggles as transformative paths towards clarity and wisdom.
