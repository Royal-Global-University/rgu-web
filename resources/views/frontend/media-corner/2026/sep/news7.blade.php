                Director, Thammasat Institute of Area Studies (TIARA), Thammasat University; Dr. Kittipong Boonkerd, South
                Asian Language Section, Faculty of Arts, Chulalongkorn University; Dr. Piyanat Soikham, Assistant to the
                President and Director, India Studies Center, Ubon Ratchathani University; and Dr. Wit Wichaidit, Associate
                Professor and Lecturer, Department of Epidemiology, Faculty of Medicine, Prince of Songkla University,
                Thailand.
