                campus yesterday, bringing together distinguished policymakers, diplomats, academics and experts from India
                and Thailand to explore new avenues of engagement between the Northeast and Thailand.
                <br><br>
                Held on the theme “Building the Northeast’s Health, Education, Youth and Enterprise Bridge with Thailand,”
                the dialogue positioned Northeast India as an important academic and people-to-people bridge between India
                and Southeast Asia, while highlighting the role of universities in creating sustained institutional
                linkages, knowledge exchange and collaborative opportunities.
                <br><br>
                The Keynote Address was delivered by H.E. Mrs Urasa Mongkolnavin, Director-General, Department of South
                Asian, Middle East and African Affairs, Ministry of Foreign Affairs, Thailand. She highlighted the
                significant potential for expanding Thailand–India cooperation, particularly in education, tourism, culture,
                training, internships and academic exchange. She also expressed optimism about translating the growing
                interest in institutional cooperation into concrete partnerships, including the possibility of formalising
                such collaboration through Memoranda of Understanding (MoUs).
                <br><br>
                The Thai delegation included senior government officials and scholars from leading Thai universities,
                including Thammasat University, Ubon Ratchathani University, Prince of Songkla University and Chulalongkorn
                University.
                <br><br>
                The Opening Session was addressed by Ambassador Riva Ganguly Das, Former Secretary (East), Ministry of
                External Affairs, Government of India; Dr. R.K. Ranjan Singh, Former Minister of State for External Affairs
                and Education, Government of India; and Shri Prashant Agrawal, Additional Secretary (South), Ministry of
                External Affairs, Government of India. The speakers underscored the importance of strengthening India’s
                engagement with countries of Southeast Asia and creating greater opportunities for regional cooperation.
                <br><br>
                The high-level academic and policy dialogue was followed by a panel discussion on “Building the Northeast’s
                Education, Youth and Enterprise Bridge with Thailand,” chaired by Ambassador Riva Ganguly Das.
                <br><br>
                The panel brought together distinguished academic and institutional leaders from India and Thailand,
                including Prof. Kaustubha Mohanti, Dean, Corporate and International Relations, Indian Institute of
                Technology; Dr. Samudra Gupta Kashyap, Chancellor, Nagaland University; Dr. Nalin Mehta, Director,
