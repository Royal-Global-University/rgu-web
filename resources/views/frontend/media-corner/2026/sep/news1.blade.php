                <span class="fw-bold"> GUWAHATI, September 3, 2026: </span>The Assam Royal Global University (RGU) brought
                the year-long celebrations marking the birth centenary of legendary cultural icon Dr. Bhupen Hazarika to a
                befitting close today with reflection, conversation, poetry and music, celebrating the life, works and
                enduring legacy of the Bard of the Brahmaputra.
                <br><br>
                A major highlight of the occasion was the release of Dr. Bhupen Hazarika: The Man and His Times by Dr. Manas
                Chaudhuri, Padma Shri awardee, Managing Director and former Editor of The Shillong Times. Edited by Dr
                Prasanta J Baruah & Dr Stuti Goswami, the publication marks another significant contribution by the Bhupen
