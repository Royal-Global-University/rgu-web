                times of Dr. Bhupen Hazarika.
                <br><br>
                Welcoming the gathering, Prof. Amarjyoti Choudhury, Professor Emeritus and Chair Professor, Dr. Bhupen
                Hazarika Centre for Creativity recalled a personal interaction with Dr. Hazarika from his younger days, and
                spoke about the creative challenge that Bhupen Hazarika represented. He recalled having once asked Bhupen
                Hazarika how he knew that something creative was about to emerge from within him. Reflecting on the question
                decades later, Prof. Choudhury underlined the extraordinary creative vision and restless imagination that
                defined Bhupen Hazarika’s life and work.
                <br><br>
                The occasion featured an address by Dr. Manas Chaudhuri, who shared several memories of Dr. Hazarika’s
                association with Shillong. Recollecting the political and cultural milieu of Shillong in the 1970s, Dr.
                Chaudhuri referred to Dr. Hazarika’s tenure as an independent legislator in the Shillong Assembly in 1974.
                He described him as a magnetic personality and recalled how his songs captured the people and places around
                him, including Shillong. Referring to the song “Shillongore Monalisa Lyngdoh,” he reflected on the
                distinctive observational quality of Dr. Hazarika’s artistic expression.
                <br><br>
                The programme also featured a poignant poem recitation by Sattyakee D'com Bhuyan, adding a literary
                dimension to the evening’s tribute. The musical segment brought together a distinguished ensemble of
                performers, including renowned singers Anirban Das, Mayukh Hazarika and Dr. Maitrayee Patar.
                <br><br>
                The closing ceremony was graced by the presence of Dr. A. K. Pansari, Chancellor, The Assam Royal Global
                University, Prof A K Buragohain, Vice Chancellor along with veteran singer Monisha Hazarika, artist Labu
                Senapati and other distinguished guests, faculty members, students and members of the university community.
