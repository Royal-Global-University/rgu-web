                <br><br>
                The 3rd edition of Sabda Kalpa, the monthly literary meet organised under the aegis of the Office of Author
                in Residence Prof. Dhrubajyoti Borah was structured as a panel discussion on short fiction and was themed
                “In Search of the Elusive Truth.” All the students and PhD scholars as well as faculty members from the
