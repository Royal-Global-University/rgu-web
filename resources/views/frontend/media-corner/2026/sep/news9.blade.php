                Ayurvedic College, Guwahati, and Sri Jintu Githart, Sahitya Akademi Yuva Puraskar awardee writer,
                translator, and editor and Assistant Professor, Handique Girls’ College, Guwahati as speakers and Dr
                Dhurjjati Sarma, academic and critic and Assistant Professor, Dept of MIL and Literary Studies, Gauhati
                University as discussant.
                <br><br>
                Prof. (Dr.) Dhruba Jyoti Borah, Author in Residence and Chief Advisor to the Chancellor, gave the welcome
                address highlighting the importance of telling stories and how short fiction as a medium often grew out of
                the everyday experiences of human life. He drew instances from his rich life experiences as he delighted the
                gathering with his profound words.
                <br><br>
                Dr. Dhurjjati Sarma, who served as discussant, opened the session by framing the theme. He spoke on the
                importance of discussing short fiction as a genre and also threw light on the rich legacy of short fiction
                in the Assamese language. The three writers shared their deliberations.
                <br><br>
                Each speaker spoke briefly on their respective journeys as creative individuals and writers of short fiction
                illuminating their creative choices they made along their journeys and their growth as writers along the
                years. The deliberations were both anecdotal and insightful.
                <br><br>
                The event gave students and faculty a chance to engage directly with practising writers, and it continued
                the River Talks Sabdakalpa series’ aim of cultivating intellectual and creative life, and the rich literary
                and cultural legacy of Assam and Northeast India and to “honour the enduring power of the spoken and written
                word” in the words of Prof. Dhrubajyoti Borah, Sahitya Akademi awardee and one of the greatest writers of
                fiction in India.
                <br><br>
                The series River Talks—Sabda Kalpa continues as a monthly event at RGU, with each edition exploring a new
                literary theme and inviting voices from across the region and beyond.
