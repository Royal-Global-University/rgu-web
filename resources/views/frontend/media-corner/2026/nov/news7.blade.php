            <p class="para1 text-dark pt-2">
                <span class="fw-bold"> GUWAHATI, November 16, 2026: </span>
                A two-day symposium titled ‘ZG Consciousness’ began today at The Assam Royal Global University (RGU),
                providing an academic and cultural platform to reflect on the enduring legacy, socio-cultural impact and
                philosophical vision of Zubeen Garg. The symposium seeks to explore how his artistic brilliance,
                humanitarian spirit and deep-rooted love for Assam can inspire collective thought, fearlessness and social
                responsibility.
                <br><br>
                Alongside the symposium, a photography exhibition titled ‘Life Through the Lens: The Dimensions of Zubeen
                Garg’ (অন্তহীন কথকতা), was inaugurated by Shri PVSLN Murty, Chairman and Managing Director of the North
                Eastern Development Finance Corporation Ltd. (NEDFi).
                <br><br>
                Organised by the Dr Bhupen Hazarika Centre for Creativity and the Department of Geography and Geoinformatics
                of RGU, in collaboration with the Zubeen Garg Foundation, the symposium is sponsored by the Central Silk
                Board and the Central Muga Eri Research and Training Institute under the Ministry of Textiles.
                <br><br>
                Addressing the inaugural session, Dr Partha Sarathi Mahanta, IPS, Commissioner of Police, Guwahati, and
                Advisor to the Zubeen Garg Foundation, said that Zubeen Garg's voice does not merely remain in people's
                memories but lives on in their hearts and minds, making him immortal. “When we listen to that voice, time
                seems to stand still. We have to understand Zubeen, who occupied a place that cannot be explained by
                popularity or musical excellence alone. He could change his musical language without changing his cultural
                identity. This, I believe, was one of his most significant contributions. He showed that an Assamese artist
                could engage with the wider world while remaining deeply rooted to home. Zubeen travelled from generation to
                generation,” he observed.
