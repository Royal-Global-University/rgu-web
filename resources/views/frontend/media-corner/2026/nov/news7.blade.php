            <p class="para1 text-dark">
            The inaugural session also featured opening remarks by Dr A.K. Pansari, Chancellor of RGU, while Prof.
            Amarjyoti Choudhury, Chair, Dr Bhupen Hazarika Centre for Creativity delivered the special address. The
            keynote address, titled ‘Understanding ZG Consciousness as an Enduring Social Conscience’, was delivered by
            Dr Palme Borthakur of RGU, who highlighted the larger social and philosophical significance of Zubeen Garg’s
            life, work and legacy.
            <br><br>
            Conceptualised and designed by Dr Palme Borthakur, the photography exhibition presents three distinct
            dimensions of Zubeen Garg's life and personality. The first section, ‘Zubeen Garg – The Photographer’,
            showcases 15 photographs captured by Zubeen himself, offering a glimpse into his perspective of the world.
            The second section, ‘Zubeen Garg – Timeless Emotions: Through Anup Baruah’s Lens’, presents his personality
            and artistic journey through the photographs of Anup Baruah. The third section, ‘Zubeen Garg’s Third Eye:
            Through Stephen Styris’s Lens’, explores another visual dimension of the multifaceted artist.
            <br><br>
            The academic deliberations on the first day are structured around three technical sessions, bringing
            together scholars, artists, journalists, cultural practitioners and representatives of the Zubeen Garg
            Foundation to examine the diverse dimensions of ZG Consciousness.
            <br><br>
            The different technical sessions were: ‘Musical Philosophy, Cultural Integration and Cinema’, ‘Humanitarianism,
            Environment and Society’, ‘Youth, Social Change and Media’, ‘Carrying the Legacy Forward: Future of ZG
            Consciousness’. An Open Discussion Forum & Student Interactions – ‘Mon Jai’ (মন যায়) received enthusiastic
            participation.
            <br><br>
            The symposium will continue on November 17, with further deliberations on the legacy of Zubeen Garg and its
            relevance to contemporary society.
