                Prof. Sajal Nag, Distinguished Professor, Department of History, Royal Global University.
                <br><br>
                The inaugural session concluded with a vote of thanks by Dr Susmita Hazarika, Associate Professor,
                Department of History, RGU, and Local Secretary of the 45th NEIHA Session.
                <br><br>
                The three-day session is witnessing the participation from a large number of delegates representing
                universities and academic institutions across the Northeast and other parts of India, as well as
