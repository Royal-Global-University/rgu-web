            <p class="para1 text-dark pt-2">
                <span class="fw-bold"> GUWAHATI, November 28, 2026: </span>
                The Assam Royal Global University (RGU) made its debut in theatre with Heraise (Lost), its first-ever
                theatrical production, presented by the Dr. Bhupen Hazarika Centre for Creativity (DBHCC) in association
                with D’Passion Collective at D’Royal Auditorio, on November 27. The one-hour bilingual production received
                an enthusiastic response from a packed auditorium.
                <br><br>
                Written by eminent theatre personality Prof. Amarjyoti Choudhury, Professor Emeritus and Chair of the Dr.
                Bhupen Hazarika Centre for Creativity, and directed by noted theatre practitioner Sattyakee D’Com Bhuyan,
                Heraise explores the gradual disappearance of traditional art forms and the urgent need to preserve Assam’s
                rich cultural heritage The bilingual production, in Assamese and English, takes Ojapali as its central
                concern, examining the vulnerability of traditional performing arts in an increasingly changing social and
                cultural landscape.
                <br><br>
                In this context, Prof. Amarjyoti Choudhury said, “The play conjures up an exciting possibility of
                reimagining traditional art forms through contemporary theatre, while drawing attention to the urgent need
                to preserve our cultural heritage. It is an invitation to reflect on what we stand to lose when our artistic
                traditions fade away, and how they can be kept alive for future generations.”
                <br><br>
                The narrative revolves around the disappearance of a maestro of an art form already struggling to retain its
                place in contemporary society. Through this premise, it explores the emotions of grief, guilt and anger that
                accompany cultural loss, while also raising the possibility of resilience and revival. Heraise invites
                audiences to reflect on what is lost when traditions gradually recede from collective memory and everyday
                life.
                <br><br>
                Bringing together the experience of established theatre practitioners and the enthusiasm of emerging
                performers, the production featured a largely young cast. While Dr. Choudhury and Bhuyan are established
                names in Assamese theatre, most of the performers, with the exception of Raghavi Dutta, were making their
                theatrical stage debuts. Raghavi is a student of the University, while Anindita Dutta and Neeta Moni Sharma
                are Assistant Professors at RGU.
                <br><br>
                Arkupal Ra Acharya, a Research Fellow at DBHCC, who had earlier made a brief cameo in a production by
                Choudhury and Bhuyan, took on his first substantial lead role. Bhaskar Jyoti Ojah, a fourth-generation
                Ojapali exponent and recipient of the 2025 Sangeet Natak Akademi Award, also made his dramatic stage debut.
                <br><br>
                The production featured a special appearance by Dr. Amarjyoti Choudhury, with Mayukh Hazarika contributing
                the diegetic song. Background music was composed by Bhaskar Jyoti Ojah, while the lighting was designed by
                Bhaskar Boruah, a graduate of the National School of Drama (NSD). The overall design and direction were by
                Sattyakee D’Com Bhuyan.
                <br><br>
                The director's note highlighted the importance of keeping traditional art forms relevant to contemporary
                life rather than allowing them to retreat into the pages of history. The production also sought to explore
                the possibilities of theatre through a distinctive design and a fresh interpretation of an indigenous
                performance tradition.
                <br><br>
                As the first theatre production of Royal Global University, Heraise marks an important initiative by the Dr.
                Bhupen Hazarika Centre for Creativity towards promoting theatre and providing a platform for creative
                expression and cultural engagement within the university. The enthusiastic audience response to this maiden
                production has set an encouraging note for RGU’s future theatrical endeavours.
