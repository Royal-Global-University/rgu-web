            <p class="para1 text-dark pt-2">
                <span class="fw-bold"> GUWAHATI, November 5, 2026: </span>
                The Second Dr Bhupen Hazarika Oration Series, organised by the Dr Bhupen Hazarika Centre for Creativity at
                The Assam Royal Global University (RGU), featured an inaugural lecture by Prof. Alak Kumar Buragohain, Vice
                Chancellor of RGU, who explored the legendary cultural icon’s role as a public intellectual and an organic
                intellectual in the context of Antonio Gramsci’s political philosophy.
                <br><br>
                The programme began with a welcome address by Prof. Amarjyoti Choudhury, Chair and Emeritus Professor at the
                Dr Bhupen Hazarika Centre for Creativity, who highlighted the Centre’s initiatives and its commitment to
                promoting creative and intellectual engagement.
                <br><br>
                A key highlight of the programme was the launch of SonicDiff, an indigenous software application developed
                in-house at RGU by Sashanka Baruah, Head of Information Technology, for the Centre. The application seeks to
                bring objective and measurable evidence to the study of Assam’s devotional music by examining Borgeet and
                Bhaona alongside Hindustani and Western musical traditions through standard methods of voice science. The
                initiative provides RGU with an in-house research capability to document, study and preserve the region’s
                musical heritage.
                <br><br>
                In his lecture, Prof. Buragohain examined Hazarika’s contribution through the concept of the “organic
                intellectual” articulated by Italian Marxist thinker Antonio Gramsci. He explained that an organic
                intellectual helps a social group understand its lived experiences, articulate its concerns and develop the
                capacity to act. Hazarika, he observed, used music not merely as an artistic medium but as a means of making
                people conscious of social realities, inequalities and the dignity of labour.
                <br><br>
                Prof. Buragohain observed that Hazarika’s performances brought socially conscious ideas to mass audiences,
                making music a medium through which people could engage with questions of inequality, justice and human
                dignity. By combining cultural expression with social commentary, Hazarika encouraged audiences to look
                beyond entertainment and reflect on the realities around them.
                <br><br>
                He further noted that Hazarika’s intellectual and artistic evolution was shaped by the legacy of Jyotiprasad
                Agarwala and Bishnu Prasad Rabha, whose creative traditions were closely connected with social concerns. His
                academic engagement with mass communication and adult education during his doctoral work at Columbia
                University also informed his understanding of the role of communication in social transformation.
                <br><br>
                Emphasising Hazarika’s enduring relevance, Prof. Buragohain said that his songs gave form to people’s
                concerns and enabled them to remember, share and make those concerns their own. He described Hazarika as a
                catalyst who used the power of music to sensitise society and bring marginalised voices into public
                consciousness.
