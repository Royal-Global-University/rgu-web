                <span class="fw-bold"> GUWAHATI, November 26, 2026: </span>
                A two-day National Conference on “Cryptogamic Diversity, Conservation and Sustainable Utilization” commenced
                today at The Assam Royal Global University (RGU), bringing together eminent scientists, academicians,
                researchers and students to discuss emerging developments in the study, conservation and sustainable
                utilisation of cryptogamic organisms.
                <br><br>
                Organised by the Department of Botany, RGU, in collaboration with the Indian Lichenological Society,
                Lucknow, and CSIR–National Botanical Research Institute (NBRI), Lucknow, the conference is being held on
                November 26 and 27 at the university campus.
                <br><br>
                The conference aims to provide an interdisciplinary platform for deliberations on recent advancements in the
                diversity, taxonomy, ecology, evolution, conservation and sustainable utilisation of cryptogams, including
                algae, fungi, lichens, bryophytes and pteridophytes. It seeks to encourage scientific exchange and
                collaborative research on these often-overlooked but ecologically significant groups of organisms.
                <br><br>
                The inaugural session featured an introduction to the conference by Dr Gaurav Kumar Mishra, Scientist,
                CSIR–NBRI, Lucknow. Prof. Alak Kumar Buragohain, Vice-Chancellor, RGU, addressed the gathering, while Prof.
                Saroj Kanta Barik, Vice-Chancellor, North-Eastern Hill University (NEHU), Shillong, attended as the Chief
                Guest and delivered the inaugural address.
                <br><br>
                Earlier, Dr Bandana Nabis Das, Professor, Department of Botany, Royal School of Life Sciences and Computing
                (RSLSC), RGU, delivered the welcome address. The session also featured the presentation of Lifetime
                Achievement Awards and the felicitation of Fellows of the Indian Lichenological Society.
                <br><br>
                The academic programme includes several distinguished lectures by eminent experts. Dr D.K. Upreti delivered
                the Presidential Lecture on ‘General Account of Lichens’, while Dr Anupam Dixit delivered the Dr D.D.
                Awasthi Memorial Lifetime Achievement Award Lecture on ‘Teaching of Lichens in Higher Educational
                Institutions’.
                <br><br>
                Dr Sanjeeva Nayak delivered the Dr K.P. Singh Medal Lecture on ‘Assessing Nitrogen Pollution in Uttar
                Pradesh through Isotope in Lichen Pyxine cocoes’. The Plenary Lecture by Prof. Jayashree Rout focused on
                ‘Global Diversity, Cryptic Niches, and the Precarious Status of Basidiolichens’.
                <br><br>
                The conference features 25 invited lectures, alongside poster presentations for the Dr Ajay Singh Award. The
                poster presentations are being held at the Jyoti Mancha Lobby, with Dr Gaurav Kr Mishra as Chairperson and
                Dr Bhaskar Jyoti Gogoi as Co-Chairperson. Dr Anushree Baruah, Convenor of the National Conference on
                Cryptogamic Diversity, Conservation and Sustainable Utilization, Department of Botany, RGU, is coordinating
                the event.
