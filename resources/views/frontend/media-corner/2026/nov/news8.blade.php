                The two-day symposium titled ‘ZG Consciousness’ concluded today at The Assam Royal Global University (RGU).
                Organised by the Dr Bhupen Hazarika Centre for Creativity and the Department of Geography and Geoinformatics
                of RGU, in collaboration with the Zubeen Garg Foundation, the symposium provided an academic and cultural
                platform and reflected on the enduring legacy, socio-cultural impact and philosophical vision of Zubeen
                Garg.
                <br><br>
                A photography exhibition titled ‘Life Through the Lens: The Dimensions of Zubeen Garg’ was also held along
                with the symposium. Conceptualised and designed by Dr Palme Borthakur, the exhibition presented three
                distinct dimensions of Zubeen Garg’s life and personality. The first section, ‘Zubeen Garg – The
                Photographer’, showcased 15 photographs captured by Zubeen himself, offering a glimpse into his unique
                perspective of the world. The second section, ‘Zubeen Garg – Timeless Emotions: Through Anup Baruah’s Lens’,
                portrayed his personality and artistic journey through the lens of photographer Anup Baruah. The third
                section, ‘Zubeen Garg’s Third Eye: Through Stephen Styris’s Lens’, explored yet another visual dimension of
                the multifaceted artist.
