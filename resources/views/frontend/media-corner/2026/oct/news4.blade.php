            <p class="para1 text-dark pt-2">
                <span class="fw-bold">GUWAHATI, October 8, 2026: </span>Three faculty members of The Assam Royal Global
                University (RGU) have been named among the World’s Top 2% Scientists for 2026 in the global ranking
                published by published by Elsevier and Stanford University databases, on October 7.
                <br><br>
                They are Prof. Amlan Das, Department of Microbiology and Associate Dean, Research & Development; Dr.
                Faizuddin Ahmed, Assistant Professor (Research), Department of Physics; and Dr. Mukta Agrawal, Assistant
                Professor, Royal School of Pharmacy.
                <br><br>
                Further, 13 RGU faculty members are listed among the Top 1,000 Global Scholars in different research
                categories by Scholarly Index. They include Dr. Faizuddin Ahmed, Dr. Arvind Kumar Dwivedi, Dr. Biplob Borah,
                Dr. Bonisha Borah, Dr. Dilip C. Nath, Dr. Anurag Barthwal, Dr. Ayesha Aktar Khanam Choudhury, Dr. Demsai
                Reang, Dr. Bhaskar Jyoti Dutta, Dr. Arghadeep Bose, Dr. Md Hibjur Rahaman, Dr Supriyo Sen and Dr. Smrity
                Choudhury, whose research spans physics, biological sciences, chemistry, structural engineering, demography,
                environmental studies, pharmaceutical sciences, ecology, medicine, urban development and welding technology.
                <br><br>
                Dr. Faizuddin Ahmed has featured in Stanford University’s list for the seventh consecutive year, while Dr.
                Mukta Agrawal has made the list for the fifth consecutive year. Prof. Amlan Das is recognised for the second
                consecutive year.
                <br><br>
                Dr. Ahmed’s research focuses primarily on Theoretical Physics and the General Theory of Relativity. Dr.
                Agrawal works on novel drug delivery systems, nanoparticles, brain targeting and nose-to-brain drug
                delivery, particularly in treatment of Alzheimer’s disease. Prof. Das’s research areas include antimicrobial
                resistance and cancer management.
                <br><br>
