                <span class="fw-bold">GUWAHATI, October 10, 2026: </span>The Royal School of Fashion Design and Technology
                (RSFT) of The Assam Royal Global University (RGU) celebrated the creativity and talent of its graduating
                designers through ‘Synthesis 2026 – A Graduation Design Showcase’, held at the Royal Garden on the
                university campus on Friday.
                <br><br>
                The showcase brought together fashion, craftsmanship, cultural narratives, sustainability and contemporary
                design, providing the graduating students with a professional platform to present their original collections
                before an audience comprising fashion professionals, designers, creative practitioners, academicians and
                fashion enthusiasts.
                <br><br>
                The event was graced by nationally renowned fashion and costume designer Ms. Anju Modi as the Chief Guest.
                Her celebrated work extends from her eponymous fashion label to costume design for films such as Bajirao
                Mastani and Heeramandi. The fashion showcase was choreographed by Ms. Meenu Paul, prominent fashion
                choreographer, grooming expert and model coordinator from Guwahati. The event featured 14 showstoppers.
                <br><br>
                The graduating designers presented collections inspired by diverse historical, cultural and futuristic
                themes. The collections included ‘Magic in Mayhem’ by Emika Yona Wanning, ‘Ancient Egyptian Grandeur’ by
                Arya Agarwal, ‘Forbidden Love’ by Tom Ayekpam, ‘Celestial Regalia’ by Deimonlang Lapasam, ‘Me.Pilipni Bi.
                Ani’ by Taimong Marak and ‘Roaring 3020s, A Futuristic Twist of 1920s Glamour’ by Juhi Das.
                <br><br>
                The event also recognised outstanding graduating designers through awards in various categories. Emika Yona
                Wanning received the Best Graduation Project award for Magic in Mayhem, while Arya Agarwal was awarded Best
                Commercial Collection for Ancient Egyptian Grandeur.
                <br><br>
                Tom Ayekpam and Deimonlang Lapasam received the award for Most Innovative and Constructive Collection for
                Forbidden Love and Celestial Regalia, respectively. Taimong Marak received the Best Use of Traditional Craft
                award for Me.Pilipni Bi. Ani, while Juhi Das was honoured with the Best Concept and Research Collection
                award for Roaring 3020s, A Futuristic Twist of 1920s Glamour.
                <br><br>
                The awards were presented by Ms. Anju Modi; Shri Hara Kanta Baro, Regional Director, North Eastern Region,
                Ministry of Textiles, Government of Assam; Ms. Smitakshi Baruah Goswami, Director and Managing Editor,
                Pratidin Times; Ms. Indu Singh, social entrepreneur; Ms. Arita Kashyap, fashion designer, Doyna Atelier and
                Ms. Mridusmita Das Bora, Artiste Founder of COPO.
                <br><br>

                Speaking about the philosophy behind the showcase, Ms. Akriti Mazumdar, Assistant Professor, RSFT, said, “We
                are not just creating a runway; we are creating a platform for the next generation of fashion voices.” She
                said Synthesis 2026 was born from the belief that young designers needed more than a classroom to realise
                their potential.
                <br><br>
                RSFT at RGU is a contemporary centre for fashion education, design innovation and industry-oriented learning
                in Northeast India. The School offers a four-year B.Des. in Fashion Design, integrating design, technology,
                textiles, craftsmanship, sustainability and entrepreneurship. RSFT combines studio-based learning, industry
                exposure and experiential projects to nurture creative, responsible and globally conscious fashion
                professionals.
