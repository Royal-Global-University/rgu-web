                <span class="fw-bold"> GUWAHATI, November 8, 2025: </span>A three-day long international conference on “Smart Systems and Social Management” was held successfully at The Assam Royal Global University (RGU) from November 6 to 8, 2025. The conference was organised by RGU with support from GR Foundation, India and in collaboration with Springer Nature as publication partner. Sponsored by Drillbit, 2CQR and Libkart, the institutional collaborators of the Conference were: Arya Vidyapeeth College, Paschim Guwahati Mahavidyalaya and Morigaon College.
                <br><br>
                With seven broad research tracks and several themes under each track, the conference had 122 paper presentations in both physical and digital modes and researchers from across the globe, including USA, UK, Thailand, Sri Lanka, Bangladesh, Morocco, and Croatia participated.
                <br><br>
                The inaugural session of the conference was graced by Prof. Anupam Basu,  Keynote speaker and Raja Ramanna Chair Professor, Jadavpur University; Dr Nabi Hasan, Central Librarian, IIT Delhi; Prof. AK Buragohain, Vice-Chancellor, RGU, Dr Lila Kanta Borthakur, Principal, Morigaon College, Dr Manisha Bhattacharyya, Principal, Paschim Guwahati Mahavidyalaya, Prof. Shiela Bora Advisor, RGU and academicians from participating higher educational institutions.
                <br><br>
                Delivering the keynote address, Prof. Anupam Basu said, “Are our cities—and our society—becoming empathetically smart?” He traced the conceptual development of cybernetics since the 1960s and identified key dimensions of smart living. He cautioned that over-reliance on digital platforms can lead to cultural erosion, underscoring the need to root technological advancement in cultural sensitivity.
                <br><br>
                Dr. Amit Joshi, Director, GR Foundation highlighted the social impact of technology and called for research that targets the needs of India-3 to ensure inclusive technological development. In his address Prof. AK Buragohain emphasised upon the dangers of ‘intellectual darkness’ in the age of artificial intelligence but warned against over-reliance on machines.
                <br><br>
                The Plenary Sessions featured eminent participants like Prof. Bhagirathi Panda, Honorary Director, ICSSR, NE region, Prof. Mukut Sarmah, Head, Department of Library and Information Science, Assam University; Sri Aranyak Saikia, IAS and Staff Officer to Chief Secretary, Assam; Dr. Uzzal Sharma, Associate Professor, Department of Computer Science, Birangana Sati Sadhini Rajyik Viswavidyalaya, and Dr. Utpal Barman, Associate Professor, Department of Information Technology, Assam Skill University.
                <br><br>
                The technical sessions featured senior academicians and luminaries from academia as Chairpersons, and this includes Prof. Rajib Handique, Academic Registrar, Gauhati University, Prof. Jeanne Coetzer, Central University of Technology, Free State, South Africa, Dr. Priya Rai, National Law University, Delhi, Prof. Ratul Mahanta, Gauhati University, Prof. Yahya Fikri, Abdelmalek Essaâdi University. Morocco, Prof. Shubhrajeet Konwer, Gauhati University, Dr. F.R. Sumer, University NEHU Shillong, Prof. Prasenjit Das, KK Handiqui State Open University.
                <br><br>
                In this context, Dr. Hirak Jyoti Hazarika, Convener of the conference said that the conference aimed to explore how emerging technologies can drive positive societal transformation. Joint Convener Dr Stuti Goswami expressed happiness at the enthusiastic response the conference has elicited from all quarters. She said that all accepted and presented papers from ICSSSM 2025 would be published by Atlantis Press, Springer Nature in the series Advances in Intelligent Systems Research in open-access mode, thereby facilitating wider dissemination of the research contributions.
