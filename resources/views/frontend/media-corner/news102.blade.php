                Twenty Songs and Seven Portraits’ reflects the extraordinary breadth of his creativity, vast like an ocean.
                His songs remind us that love for humanity is profound and beautiful yet finds its fullest expression in
                serving and strengthening one’s own community. He truly carried an ocean of creativity within him,” he said.
                <br><br>
                Addressing the august gathering, Dr A K Pansari, Chancellor, RGU, stated, “The Centre for Creativity at
                Royal Global University, which proudly bears his name and is led by noted scholar and artist Prof Amarjyoti
                Choudhury, remains committed to preserving and advancing the legacy entrusted to us.”
                <br><br>
                Rahul Karmakar, Deputy Editor, The Hindu, reflected on Dr. Hazarika’s continuing relevance in contemporary
                socio-cultural discourse. Singer composer J. P. Das shared personal and artistic insights into the legendary
                composer’s journey.
                <br><br>
                Some of the distinguished guests present at the event include Bobeeta Sharma (Producer and Director of
                “Bhupen Da Uncut”); Dr. Nripen Borkataki, MD, USA; and Champak Borbora, Illustrator.
                <br><br>
                Describing the anthology, Sattyakee D’com Bhuyan said, “The twenty songs included in this volume have shaped
                the ethical and aesthetic imagination of our society.” The seven chapters in the book include: “Celebrating
                Life” by Pradip Acharya; “My Thirty Days with Bhupen Da in the UK” by Dr Nripen Barkataki; “77 B, Golf Club
                Road, Tollygunge: My Mother’s Memories with Bhupenmama” by Joor Baruah; “The Lyrical Chronicler: Bhupen
                Hazarika Often Did a Journalist’s Job, Musically” by Rahul Karmakar; “Shillongore Monalisa Lyngdoh” by Mitra
                Phukan; “The Legend Through My Eyes” by Mayukh Hazarika; and “Bhupen Da, Tezpur and the Culture We Lived
                With” by Dr Lakshmi Kumari Goswami. The volume is enriched with rare photographs and visuals contributed by
                noted artist and photographer Labu Senapati, while the striking cover design has been created by Champak
                Barbora.
