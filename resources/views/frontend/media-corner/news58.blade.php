                <span class="fw-bold"> GUWAHATI, October 25, 2025: </span>Dr. Nitu Borgohain, Assistant Professor in the Department of Physics, Royal School of Applied and Pure Sciences, The Assam Royal Global University (RGU), has been awarded a prestigious ISRO research grant of ₹18.24 lakhs through RAC-S@GU for a groundbreaking project in optical sensor technology.
                <br><br>
                The research project, led by Dr. Borgohain as the Principal Investigator, aims to design and simulate compact semiconductor-based, high-sensitivity optical sensors for critical space operations. These include environmental monitoring, structural health diagnostics, astrobiological exploration, and remote sensing—key areas that contribute to the advancement of India’s space exploration capabilities. The project will be supported by Prof. Goutam K. Samanta, Professor, Photonic Sciences Lab, AMOPH Division, PRL, Ahmedabad, as Co-Principal Investigator.
                <br><br>
                In this context, Dr Nitu Borgohain said, “With the emergence of hybrid sensor architectures, low-power laser systems, and AI-driven signal processing, the study envisions developing next-generation, multi-functional, intelligent sensing platforms suited for interplanetary and deep-space missions.”
                <br><br>
                Expressing his delight, Prof AK Buragohain, Vice Chancellor of the University stated, “This achievement highlights RGU’s growing emphasis on research excellence and innovation in frontier areas of science and technology, reinforcing its commitment to contributing meaningfully to India’s space research ecosystem.”
                <br><br>
                Optical sensors play a vital role in ISRO’s space missions, serving as the sensory interfaces of payloads for observation, measurement, navigation, and scientific investigation in space environments. Their miniaturized, semiconductor-based systems enable precise, non-contact acquisition of optical and spectral information from the Earth, extraterrestrial surfaces, and spacecraft surroundings.
                <br><br>
                Recent advancements in semiconductor quantum well architectures—which harness broadband light generation from supercontinuum sources and exhibit remarkable nonlinear optical properties—have opened new frontiers for developing high-performance optical sensors. Dr. Borgohain’s research seeks to contribute to this evolving field, aligning with ISRO’s vision for cutting-edge, indigenously developed space technologies.
