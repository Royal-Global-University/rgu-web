                <span class="fw-bold"> GUWAHATI, March 14, 2026: </span>The Assam Royal Global University (RGU) successfully hosted the SPIC MACAY Virasat Anubhav (SMVA) Series 2026, a four-day cultural immersion programme from March 10 to 13, aimed at promoting the rich traditions of Indian classical arts among young learners. A total of 93 RGU students participated in the technical workshops conducted during the series.
                <br><br>
                The series concluded yesterday with a historic performance by Padma Bhushan Pandit Vishwa Mohan Bhatt, the Grammy Award-winning musician and creator of the Mohan Veena. His extraordinary slide guitar performance provided a magnificent finale to the week-long celebration of India’s cultural heritage. The cultural evenings began with a powerful mime performance by Shri Moinul Haque, Pandit Rajendra Gangani’s mesmerizing Kathak recital, Vidushi Sunanda Sharma’s soulful Hindustani classical vocal concert.
                <br><br>
                In this context, Dr. Banani D Hazarika, organizing member, SMVA and Associate Dean, Student Affairs, RGU said, “The event provided students with a rare opportunity to learn directly from eminent maestros through intensive workshops and inspiring performances”. The “Anubhav” (Experience) segment of the programme featured three parallel workshops that enabled students to move beyond being spectators and become active learners of classical art forms.
                <br><br>
                A Mime Workshop was conducted by Shri Moinul Haque, a Sangeet Natak Akademi Awardee, focusing on the expressive power of silent performance. During the practical sessions, students worked on a thematic group piece titled “Man Dies When Trees Disappear,” using mime to highlight the importance of environmental conservation.
                <br><br>
                The series also included an Indian Classical Vocal Workshop conducted by Vidushi Sunanda Sharma, who introduced students to the foundational aspects of the Banaras Gharana. Another highlight was the Kathak Dance Workshop led by Pandit Rajendra Gangani, a distinguished exponent of the Jaipur Gharana. Participants explored the rhythmic intricacies of Kathak through lessons on fundamental footwork (tatkar), technical patterns, and expressive elements that define the classical dance tradition.
                <br><br>

                Maushumi Baruah George, Chairperson, Guwahati Chapter, SPIC  MACAY, said, “The SPIC MACAY Virasat Anubhav Series 2026 at RGU successfully fulfilled its mission of bridging the gap between modern education and India’s timeless artistic traditions by providing students with meaningful exposure to the country’s classical performing arts. The programme not only enriched participants artistically but also inspired them to appreciate and preserve India’s cultural legacy”.
