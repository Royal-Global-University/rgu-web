                conclave brought together eminent leaders to deliberate on some of the most urgent questions shaping the future of work.
                <br><br>
                Speaking at the inaugural panel discussion on “Minimal Input, Maximum Outcome: Has the Hustle Culture Rebranded
                Laziness?” Prof. Alaka Sarma, Academician and Co-Founder of the Akshar Foundation, emphasized the need to nurture
                children as contributors rather than dependents. “When we engage with a child from a marginalized background, our role
                is to provide an environment where the child learns to help others. By helping others, one automatically becomes a giver
                of help, not a seeker of it,” she said. Prof. Sarma further highlighted that children deprived of adequate parental
                attention often experience alienation, which technology tends to worsen—manifesting as laziness, destructiveness, or
                even suicidal tendencies. She noted the importance of conclaves like these in rethinking strategies to minimize such
                negative influences while embracing technology as an inevitable tool of progress.
                <br><br>
                The session also featured insights from Sailaja M, HR Head, Sephora, Mumbai; Abbhay Kapoor, SVP, UIL Group, Delhi; and
                Sanjay Aditya Singh, Group MD & CEO, Jettwings Airways, Guwahati. It was moderated by Bristy Srivastava, Head of the
                Royal Centre for Corporate Relations, RGU.
                <br><br>
                The second panel, “5% of Leadership, 50% of the Workforce: What’s Broken in the Climb for Women?” was addressed by Sumit
                Agarwal, DEI Champion, Kolkata; Varsha Agarwal, Vice President (Karnataka State), WICCI – Women’s Indian Chamber of
                Commerce and Industry, Bengaluru; Dr. Simanta Mohanty, Director, Janaagraha, Odisha; and Vijay Kumar Jamwal, VP HR,
                Biz2Credit, Bengaluru.
                <br><br>
                The third discussion, “Beyond the Algorithm: Reclaiming the Human in Human Resources,” included speakers Sujeet Sinha,
                Executive Vice President, Kotak Mahindra Bank, Mumbai; Nitin Jagdale, Head of Talent Acquisition, NTT DATA India, Pune;
                Govindprasad Gaonkar, Head of Human Resources, Kotak Mahindra Asset Management Company, Mumbai; and Sasmita Birabar,
                Deputy General Manager, IFFCO, Guwahati.
                <br><br>
                The fourth panel on “Funding Over Fundamentals: Has Startup Culture Outgrown Accountability?” featured Rajdeep Ghosh,
                Tech Talent Acquisition Leader, Amazon, Bengaluru; David Pratim Gogoi, Co-Founder & Director, Zerund Bricks, Guwahati;
                and Nitin Bajpai, Circle CEO, Jio.
                <br><br>
                Throughout the conclave, participants engaged in critical discussions on rethinking hustle culture, holding startups
                accountable, advancing women’s representation in CXO roles, redefining HR in the age of algorithms, and preparing Gen Z
                for the ethical complexities of professional life.
