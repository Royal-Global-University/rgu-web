                <span class="fw-bold"> Guwahati, August 14, 2025: </span> “If we are confident to face the real world and understand each other as fellow human beings, then our education has
                been purposeful. We need Communication, Collaboration, Critical Thinking, and Creativity to make a successful living.”
                This was stated here today by Prof. (Dr.) Devendra Jalihal, Director of the Indian Institute of Technology, Guwahati,
                while addressing the Deeksharambh Programme for PG and Ph.D. students at The Assam Royal Global University (RGU).
                <br><br>
                Speaking to a packed hall of new students, Prof. Jalihal remarked, “We are living in an era of communication devices
                that didn’t exist even 15 years ago. I feel that in the process of having these devices, we have lost the art of
                communication. We no longer talk to each other the way generations of people used to—sharing their joys and sorrows.
                They may not have been materially rich, but they were culturally, emotionally, and intellectually rich.”
                <br><br>
                Expressing concern, he said, “Today’s generation that I encounter as a teacher or administrator sends emails with
                well-formed sentences, but not necessarily because their writing skills have improved—it is because there is ChatGPT.”
                <br><br>
                Quoting 21st-century historian and philosopher Prof. Yuval Noah Harari, Prof. Jalihal emphasized that we need the “3 Cs”
                for a successful life: Communication, Collaboration, and Critical Thinking. He stressed the importance of communicating
                as fellow human beings, adding, “Language is not a problem if you are well grounded in your own language. My request to
                you is to focus on language, thoughts, reading, and writing.”
                <br><br>

                Urging students to collaborate with one another, he said, “This is the only way to solve the problems of the 21st
                century. If we are confident to face the real world and understand each other as fellow human beings, then our education
                has been purposeful.”
                <br><br>
                Highlighting India’s rich educational heritage, Prof. Jalihal noted, “Just 225 years ago, India had more books in its
                libraries than anywhere else in the world. The literacy rate in India in 1800 was 30%, whereas in England, which was
                already ruling, it was only 14%.” Remembering Mahatma Gandhi, he described the Indian education system as “a beautiful
                tree.”
                <br><br>
                He further said that one should always be able to question and think. Referring to the epic Mahabharata, which he called
                an “encyclopedic book of philosophy told through stories,” he highlighted that Indian society has sustained itself
                through creative storytelling. Prof. Jalihal concluded by urging students to apply critical thinking and creativity for
                a successful life.
