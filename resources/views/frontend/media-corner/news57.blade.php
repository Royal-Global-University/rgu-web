                The workshop brought together leading experts and academicians from across India, including delegates from Regional Institute of Ophthalmology (GMCH), The Assam Downtown University, and PEWS Group of Institutions. The event saw enthusiastic participation from over 350 optometry students and practitioners, both from RGU and other institutions, creating a collaborative learning platform.
                <br><br>
                Over the four days, participants engaged in high-impact academic and clinical sessions, such as Contact Lens Workshop, Corporate Hands-on Training, Low Vision & Rehabilitation, Clinical Case Discussions, Binocular Vision Workshop. The workshop featured an eminent panel of speakers, including Mr. Gagan Sahni, Technical Director, Silverline Laboratory Pvt. Ltd. & Purecon Lenses Pvt. Ltd., New Delhi; Dr. Harsha Bhattacharjee; Prof. (Dr.) Aditya Goyal, Principal, Sankara College of Optometry, Bengaluru; Dr. Sumita Sarma Borthakur, Senior Ophthalmologist, Namecare Hospital; Dr. Jayanta Kumar Das, Chairman, Netra Jyoti Eye Hospital and Mr. Muralidhar Attal, CEO, OM Tao Scientific Apparatus.
                <br><br>
                The sessions were designed to bridge academic knowledge with clinical expertise and industry applications, thereby enhancing the professional competencies of aspiring optometrists. The event concluded with certificate distribution, marking the successful completion of four days of advanced learning, hands-on training, and professional networking in the field of optometry. The organizers expressed gratitude to all resource persons, participants, and collaborators for their contribution toward making the workshop a resounding success.
