                <span class="fw-bold"> GUWAHATI, November 16, 2025: </span>The Department of English, The Assam Royal Global University (RGU), in collaboration with Sangeet Natak Akademi, New Delhi, organised “Reminiscing Sudhakantha: A Colloquium on His Life and Variegated Contributions” to commemorate the birth centenary of Dr Bhupen Hazarika. Held yesterday, the day-long programme brought together scholars, journalists, authors, and cultural figures from across the region and beyond to reflect upon the multifaceted legacy of the legendary artist, poet, and humanist.Dr Sandhya Purecha, Chairman of the Sangeet Natak Akademi, joined the gathering virtually.
