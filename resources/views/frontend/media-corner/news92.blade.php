                <span class="fw-bold"> GUWAHATI, January 29, 2026: </span>The immense biodiversity of Northeast India holds strong potential to drive the region’s bioeconomy through the growth of biomanufacturing industries across multiple sectors, said Dr. Srinivas V. Kaveri, Director of Research at INSERM (French National Centre for Scientific Research), Paris, while addressing the inaugural session of the International Conference on “Transforming Northeast India from Biodiversity Hotspot to Biomanufacturing Hotspot: A BioE3 Perspective” today at The Assam Royal Global University (RGU).
                <br><br>
                The two-day conference from 29 to 30 January 2026 has been sponsored by the Anusandhan National Research Foundation (ANRF) and the Defence Research and Development Organisation (DRDO), Government of India. It brings together leading scientists, academicians, and industry experts to deliberate on the BioE3 Policy—Biotechnology for Economy, Environment, and Employment—which aims to transform India’s biomanufacturing sector through innovation, sustainability, and high-quality production.
                <br><br>
                Delivering the keynote address, Dr. Srinivas spoke on the immune response and adaptive immune system, highlighting the expanding role of Intravenous Immunoglobulin (IVIG) therapy in treating a wide range of diseases. He emphasized that the development of a robust plasma industry is crucial for advancing immunotherapy and biotechnology, stressing the importance of regular blood donation to support future medical innovations. According to him, immunotherapy represents a major frontier of modern medicine, and biotechnology will play a decisive role in shaping healthcare solutions of the future. Referring to the immense untapped potential of the North East India, a globally recognized biodiversity hotspot, he stated that the biodiversity of the region carries future for bioeconomy here.
                <br><br>
                Addressing the inaugural session, Prof. A. K. Buragohain, Vice Chancellor, RGU emphasised that Northeast India, being a biodiversity hotspot, must strategically harness its ecological wealth for sustainable bioeconomic growth, remarking that “the future technology will be biotechnology.” Earlier, Prof. Anupam Chatterjee, Dean, RSBSC, RGU and Advisor to the Conference, delivered the welcome address.
                <br><br>
                Today’s plenary lectures were delivered by Prof. Shekhar C. Mande, President, INSA, Former Director General, CSIR and Dr. K.K. Narayanan, Managing Director, Sthayika Seeds Pvt. Ltd., Bangalore. Other eminent speakers of the Conference include: Prof. M. Prakash Hande, National University of Singapore; Professor Gareth Jenkins, Institute of Life Science, Swansea, UK; Dr Sanjai K Dwivedi, Scientist 'G' & Director (DoP) DRDO, New Delhi; Dr. Pronobesh Chattopadhyay, Scientist G, Defence Research Laboratory DRDO, Tezpur; Dr. Probodh Borah, Director of Research, Assam Veterinary and Fishery University, Guwahati and Prof. Utpal Borah, Head, Department of Biosciences and Bioengineering, IIT-Guwahati.
