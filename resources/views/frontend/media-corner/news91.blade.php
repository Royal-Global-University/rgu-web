                address by Mr. Apurba Kumar Sharma, Senior Advocate and Chairman, Executive Committee, Bar Council of India.
                “With Royal Global University hosting this landmark national event, Guwahati is poised to emerge as a
                significant hub for legal education and advocacy in the country”, she added.
