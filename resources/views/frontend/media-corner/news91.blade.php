                from premier law institutions, ensuring a high standard of evaluation and academic rigor. “Till now, 65
                teams from various parts of India have registered to participate in the competition. The Final Round will be
                graced by Hon’ble Mr. Justice Kalyan Rai Surana, Judge, Gauhati High Court, Mr. Dilip Majumdar, Senior
                Advocate, Gauhati High Court, Dr. Shaiwal Satyarthi, Professor of Law, University of Delhi”, he added.
                <br><br>
