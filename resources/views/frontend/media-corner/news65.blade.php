                <span class="fw-bold"> GUWAHATI, November 10, 2025: </span>The Forest Man of India, Padma Shri awardee Shri Jadav Payeng, has made a heartfelt appeal to create a forest in every district of Assam in memory of the late legendary artist Zubeen Garg, who was known for his love and compassion for nature, animals, and humanity. “If we create a forest in Zubeen’s name in every district, people will breathe oxygen in his memory. It will be an evergreen tribute to the nature-loving artist,” Shri Payeng said while addressing BOTANIQUE 3.0, the annual fest of the Department of Botany, The Assam Royal Global University (RGU), held on the university campus today.
                <br><br>
                Delivering his talk on “My Journey from a Single Sapling to a Living Forest,” Shri Payeng inspired students by sharing his life’s mission of reforestation and ecological restoration. He highlighted how one individual, through consistent effort and dedication, can transform a barren landscape into a thriving forest ecosystem. His story—beginning with a single sapling planted decades ago that has now grown into a vast forest—stood as a powerful testimony to the impact of individual responsibility toward the environment.
                <br><br>
                The Forest Man urged that Environmental Studies must be made compulsory at the university level, emphasizing that education plays a vital role in shaping environmentally responsible citizens. He passionately stated, “Nature is God, and God is Nature,” reminding the audience of the deep spiritual connection between humanity and the natural world.
                <br><br>
                Speaking on environmental governance, Shri Payeng stressed the need for Indian Forest Service (IFS) officers and environmental leaders from the North-East who truly understand the region’s geography, biodiversity, and socio-cultural context. “People from outside often fail to understand the land and its resources and are more money minded. Our forests need caretakers who belong to the soil,” he added.
                <br><br>
                During his address, Shri Payeng also reflected on the role of culture and language in sustainable development, saying, “Cultural development is essential for the progress of the country. Our mother tongue is our identity and protecting it is part of protecting our roots.” He urged the youth to follow Zubeen Garg’s legacy by taking up activities that contribute to environmental protection, such as tree plantation drives, animal welfare, and preservation of biodiversity. The session concluded with an enthusiastic interactive discussion between Shri Payeng and RGU students, where he encouraged them to take small, consistent actions toward creating a greener planet.
