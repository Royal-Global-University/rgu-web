        function rguForestryToggleAccordion(button) {

            const item = button.closest(
                ".rgu-educationn-accordion-item"
            );

            const arrow = button.querySelector(
                ".rgu-educationn-accordion-arrow"
            );

            const isActive = item.classList.contains("active");


            /* Close all accordion items */

            document
                .querySelectorAll(
                    ".rgu-educationn-accordion-item"
                )
                .forEach(function(otherItem) {

                    otherItem.classList.remove("active");

                    const otherArrow =
                        otherItem.querySelector(
                            ".rgu-educationn-accordion-arrow"
                        );

                    if (otherArrow) {

                        otherArrow.classList.remove(
                            "fa-chevron-up"
                        );

                        otherArrow.classList.add(
                            "fa-chevron-down"
                        );

                    }

                });


            /* Open selected item */

            if (!isActive) {

                item.classList.add("active");

                arrow.classList.remove(
                    "fa-chevron-down"
                );

                arrow.classList.add(
                    "fa-chevron-up"
                );

            }

        }



