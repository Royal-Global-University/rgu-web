            <p style="text-align: justify;" class="para1 text-dark">
                The seminar on climate change and livelihood in the Northeast India seeks to unearth
                climate histories and dynamics intertwined with the environment and livelihood. It aims to
                assemble together scholars, academicians, community leaders, and policy makers to discover
                how local institutions and community can act as agents of change, and resist climate change.
                As climate change-induced risks loom large, highlighting the experiences of the region form a
