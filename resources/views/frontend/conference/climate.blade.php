            <h2 class="headd3 fw-bold kd-title-ani kd-split-text pt-3 pb-3" style="color: #27467A; font-weight: 900;">
                Climate Change in the<span style="color: #FF9A1E; font-weight: 500;"> Context of Northeast India</span>
            </h2>

            <p style="text-align: justify;" class="para1 text-dark">
                Northeast India is vulnerable to the impacts of climate change. While frequent floods,
                soil erosion, landslides, biodiversity reduction, and loss of livelihood displace populations, the
                projection for the future is worse than this reality. Unusual heatwaves have become common
                in many areas of the region. Different segments of the population being forced to live through
                such unprecedented heat waves, results in long term impacts. With schools shut for children,
                and the occupational activities of adults disrupted, climate anxiety and frustration have become
                unavoidable. Other climate related concerns range from devastating floods affecting people
                across the Brahmaputra and Barak valley, health and sanitation challenges, loss of livestock,
                human-wildlife conflicts due to fragmented habitats, to crop failures. The causes of the crisis
                have to be identified. Driven by focus on economic growth, progress through infrastructure
                development is attaining momentum in the Northeast. However, such ideas of development
                have increased the environmental burden like forest clearance, riverbank erosion, pollution,
                and disruption of the livelihood of forest-dependent and riverine communities.
                <br>
                Amid such a crisis, people in power tend to take over the local voices and their agency
                for protesting. The indigenous and local communities across the region are frequently deprived
                of the gains of climate actions or development. It is part of the marginality and exclusion of the
                Northeast that the region continues to remain an outlier to mainstream India. While
                communities confront the environmental impacts through indigenous knowledge and
                adaptations, they are never free from the paradoxical situations. Does that mean that the people
                of the region should continue to face injustice and unequal representation? The climate impacts
                cannot be understood without factoring in the geographical, hydrological, and developmental
                setting of the Northeast. It is therefore, crucial to consider the many lives of the region and
                their creation of collective space amidst high-level uncertainty of climate projection.
                <br>
                It is, therefore, crucial to factor in the causes of climate change as well as possible
                solutions, not only technical but also those emanating from popular knowledge. The Northeast
                is today the main source of timber for forest-based industries in much of India. Deforestation
                in the catchment areas of the Brahmaputra and its subsidiaries has resulted in the level of the
                riverbed rising and the consequent frequent floods. Urbanisation and cutting of hills in the
                “young Himalayas” further intensify the problem. Erosion of land on the river banks adds to
                the problem. Ultimately it is the poor whose carbon footprints are the weakest in this crisis,
                suffer the most both economically and through the erosion of their social systems. Solutions
                have to be found to this crisis, not just technical but also based on socio-economic equity.
            </p>

            <h2 class="headd3 fw-bold kd-title-ani kd-split-text pt-3 pb-3" style="color: #27467A; font-weight: 900;">
                Conclusion
