            </h2>

            <p style="text-align: justify;" class="para1 text-dark">
                Discussion at the seminar will be divided into six technical sessions. Researchers and
                scholars are invited to present papers at these sessions. The presentations will focus on the
                impacts on the environment, no doubt, but equally on socio-economic issues such as food
                security, health and a cohesive social organisation. Solutions too cannot be merely technical
                and physical environment based. Also those based on popular knowledge, have to be studied
                for a lasting solution. One can broadly divide the seminar into the following technical sessions.
            </p>

            <p style="text-align: justify;" class="para1 text-dark fw-bold">
                Technical Session I: Anthropogenic causes of climate change: Environment and Society in Northeast India
            </p>

            <p style="text-align: justify;" class="para1 text-dark">
                What have been the major causes of climate change in the Northeast? What has caused
                more frequent floods, droughts, land erosion and landslides than in the past? How have human
                activities posed detrimental to the environment? What causes sequential exhaustion of the
                natural resources and the consequent environmental impacts as well as socio-economic
                consequences on the poor in particular? The poor with very few carbon footprints are often
                blamed for the environmental consequences of climate change. What is the role of the pattern
                of development, of the rich and of the poor?
            </p>

            <p style="text-align: justify;" class="para1 text-dark fw-bold">
                Technical Session II: Environmental consciousness and remedial protocols
            </p>

            <p style="text-align: justify;" class="para1 text-dark">
                How has the world convened a way in the form of Treaties, Protocols, and Accords to
                counter environmental challenges? What remedial measures are taken up in the national and
                global level? What goals are being set to help people and non-human beings from the clutch of
                environmental damage? How to protect climate refugees who are displaced by effects of
                extreme weather conditions?
            </p>

            <p style="text-align: justify;" class="para1 text-dark fw-bold">
                Technical Session III: Climate induced change and its impact on health
            </p>

            <p style="text-align: justify;" class="para1 text-dark">
                Health impacts are visible in air borne as well as water-borne diseases such as respiratory
                and others. What diseases are visible because of climate change and what solutions are being
                attempted in the healthcare system meant for the well off, in the government healthcare system
                and through the adaptation and resilience and traditional health practices?
            </p>

            <p style="text-align: justify;" class="para1 text-dark fw-bold">
                Technical Session IV: Climate Change, Food Security, and sustainable agrarian practices
            </p>

            <p style="text-align: justify;" class="para1 text-dark">
                Crop loss caused by frequent floods, droughts, land erosion and desertification are among
                the causes that result in food shortages and nutritional deficiencies. What can be attempted as
                a solution to this? What role can indigenous food systems play in the promotion of sustainable
                land use? What does adopting climate-resilient agriculture mean?
            </p>

            <p style="text-align: justify;" class="para1 text-dark fw-bold">
                Technical Session V: Community awareness and pedagogy
            </p>

            <p style="text-align: justify;" class="para1 text-dark">
                Exploring pedagogies for climate change is an imperative today. How does one help bring
                about awareness among various classes and decision-makers, of the causes and the need to
                search for sustainable alternatives? What type of educational programmes are feasible? What
                inter-disciplinary approaches, community engagement and other forms are viable?
            </p>

            <p style="text-align: justify;" class="para1 text-dark fw-bold">
                Technical Session VI: Open session: Search for Solutions
            </p>

            <p style="text-align: justify;" class="para1 text-dark">
