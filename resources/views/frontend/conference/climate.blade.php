                mechanisms for climate change in Northeast India. The role of local governance institutions
                needs to be studied, so also the future of forest-dependent livelihoods, the role of development
                and conflicts in it and the solution to deforestation and unsustainable land use. One needs to go
                beyond official and technical solutions to what the farmers, the rural population and the
                traditional forest dwellers are practising. Can these practices contribute to a solution?
